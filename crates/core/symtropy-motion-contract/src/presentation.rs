/// Compose a new style profile from compatible parent profiles and an explicit edit plan.
/// Identity and skeleton anchors are inherited unchanged from the primary parent.
pub fn compose_avatar_style_profile(
    primary_parent: &AvatarStyleProfile,
    additional_parents: &[AvatarStyleProfile],
    plan: &AvatarStyleCompositionPlan,
) -> Result<AvatarStyleProfile, AvatarStyleContractError> {
    primary_parent.validate()?;
    if additional_parents.len() + 1 > MAX_AVATAR_STYLE_PARENT_PROFILES {
        return Err(AvatarStyleContractError::ResourceLimitExceeded(
            "composition parent profiles",
        ));
    }
    valid_identifier(&plan.profile_id, "composition.profile_id")?;
    valid_identifier(&plan.context_id, "composition.context_id")?;

    let mut parent_ids = vec![primary_parent.profile_id.clone()];
    let mut parent_by_id = std::collections::BTreeMap::<String, &AvatarStyleProfile>::new();
    parent_by_id.insert(primary_parent.profile_id.clone(), primary_parent);
    for parent in additional_parents {
        parent.validate()?;
        if parent.identity_ref != primary_parent.identity_ref
            || parent.identity_anchor_sha256 != primary_parent.identity_anchor_sha256
            || parent.skeleton_signature_sha256 != primary_parent.skeleton_signature_sha256
        {
            return Err(AvatarStyleContractError::ParentIdentityMismatch);
        }
        parent_ids.push(parent.profile_id.clone());
        if parent_by_id
            .insert(parent.profile_id.clone(), parent)
            .is_some()
        {
            return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                "composition parent profile ids",
            ));
        }
    }
    parent_ids.sort();
    if parent_ids.windows(2).any(|pair| pair[0] == pair[1]) {
        return Err(AvatarStyleContractError::UnsortedOrDuplicate(
            "composition parent profile ids",
        ));
    }
    if parent_ids.binary_search(&plan.profile_id).is_ok() {
        return Err(AvatarStyleContractError::InvalidCompositionPlan(
            "new profile id must differ from every parent",
        ));
    }
    if additional_parents.len() > 0 && plan.family_id.is_none() {
        return Err(AvatarStyleContractError::InvalidCompositionPlan(
            "hybrid composition requires an explicit output style family",
        ));
    }

    if plan.parent_influences.len() != parent_ids.len() {
        return Err(AvatarStyleContractError::InvalidCompositionPlan(
            "every parent profile must have exactly one composition weight",
        ));
    }
    let mut previous_parent: Option<&str> = None;
    let mut weight_sum = 0.0_f64;
    let mut weighted_parents = Vec::with_capacity(plan.parent_influences.len());
    for influence in &plan.parent_influences {
        valid_identifier(
            &influence.profile_id,
            "composition.parent_influence.profile_id",
        )?;
        if previous_parent.is_some_and(|previous| previous >= influence.profile_id.as_str()) {
            return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                "composition parent influences",
            ));
        }
        if !influence.weight.is_finite() || influence.weight <= 0.0 || influence.weight > 1.0 {
            return Err(AvatarStyleContractError::InvalidCompositionPlan(
                "parent influence weights must be finite and in (0, 1]",
            ));
        }
        let Some(parent) = parent_by_id.get(influence.profile_id.as_str()) else {
            return Err(AvatarStyleContractError::InvalidCompositionPlan(
                "parent influence must reference a supplied parent profile",
            ));
        };
        weighted_parents.push((*parent, influence.weight));
        weight_sum += influence.weight;
        previous_parent = Some(&influence.profile_id);
    }
    if plan
        .parent_influences
        .iter()
        .map(|influence| influence.profile_id.as_str())
        .ne(parent_ids.iter().map(String::as_str))
        || !weight_sum.is_finite()
        || (weight_sum - 1.0).abs() > 1.0e-9
    {
        return Err(AvatarStyleContractError::InvalidCompositionPlan(
            "parent influences must match the sorted parent set and sum to one",
        ));
    }

    let weighted = |select: fn(&AvatarStyleProfile) -> f64| {
        weighted_parents
            .iter()
            .map(|(parent, weight)| select(parent) * weight)
            .sum::<f64>()
    };
    let mut composed = primary_parent.clone();
    composed.profile_id = plan.profile_id.clone();
    composed.context_id = plan.context_id.clone();
    composed.parent_profile_ids = parent_ids;

    // Blend continuous profile dimensions with the declared parent weights.
    composed.visual.realism = weighted(|profile| profile.visual.realism);
    composed.visual.stylization = weighted(|profile| profile.visual.stylization);
    composed.visual.detail_density = weighted(|profile| profile.visual.detail_density);
    composed.visual.ornamentation = weighted(|profile| profile.visual.ornamentation);
    composed.visual.silhouette_expressivity =
        weighted(|profile| profile.visual.silhouette_expressivity);
    composed.motion.gesture_amplitude = weighted(|profile| profile.motion.gesture_amplitude);
    composed.motion.movement_expressivity =
        weighted(|profile| profile.motion.movement_expressivity);
    composed.motion.transition_smoothness =
        weighted(|profile| profile.motion.transition_smoothness);
    composed.motion.idle_motion_intensity =
        weighted(|profile| profile.motion.idle_motion_intensity);
    composed.motion.locomotion_stylization =
        weighted(|profile| profile.motion.locomotion_stylization);
    composed.expression.facial_expressivity =
        weighted(|profile| profile.expression.facial_expressivity);
    composed.expression.gaze_expressivity =
        weighted(|profile| profile.expression.gaze_expressivity);
    composed.expression.blink_intensity = weighted(|profile| profile.expression.blink_intensity);
    composed.expression.viseme_intensity = weighted(|profile| profile.expression.viseme_intensity);

    // Blend matching open-ended parameters by their contributing parent weights.
    // Parameters absent from a parent are not treated as zero; their remaining weights
    // are renormalized, avoiding an invented default value.
    let mut parameter_blends = std::collections::BTreeMap::<String, (f64, f64)>::new();
    for (parent, weight) in &weighted_parents {
        for parameter in &parent.visual.parameters {
            let entry = parameter_blends
                .entry(parameter.parameter_id.clone())
                .or_insert((0.0, 0.0));
            entry.0 += parameter.value * weight;
            entry.1 += weight;
        }
    }
    composed.visual.parameters = parameter_blends
        .into_iter()
        .map(
            |(parameter_id, (weighted_value, contributing_weight))| AvatarStyleParameter {
                parameter_id,
                value: weighted_value / contributing_weight,
            },
        )
        .collect();

    // Categorical style choices are explicit, never numerically averaged.
    if let Some(value) = plan.family_id.as_deref() {
        valid_namespaced_identifier(value, "composition.family_id")?;
        composed.visual.family_id = value.to_string();
    }
    if let Some(value) = plan.palette_id.as_deref() {
        valid_namespaced_identifier(value, "composition.palette_id")?;
        composed.visual.palette_id = value.to_string();
    }
    if let Some(value) = plan.material_language_id.as_deref() {
        valid_namespaced_identifier(value, "composition.material_language_id")?;
        composed.visual.material_language_id = value.to_string();
    }

    // Explicit scalar edits are applied after the weighted blend.
    let mut previous_dimension = None;
    for edit in &plan.scalar_edits {
        let tag = avatar_style_dimension_tag(edit.dimension);
        if previous_dimension.is_some_and(|previous| previous >= tag) {
            return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                "composition scalar edits",
            ));
        }
        validate_unit_interval(edit.value, "composition.scalar_edit.value")?;
        match edit.dimension {
            AvatarStyleDimension::VisualRealism => composed.visual.realism = edit.value,
            AvatarStyleDimension::VisualStylization => composed.visual.stylization = edit.value,
            AvatarStyleDimension::VisualDetailDensity => {
                composed.visual.detail_density = edit.value
            }
            AvatarStyleDimension::VisualOrnamentation => composed.visual.ornamentation = edit.value,
            AvatarStyleDimension::VisualSilhouetteExpressivity => {
                composed.visual.silhouette_expressivity = edit.value;
            }
            AvatarStyleDimension::MotionGestureAmplitude => {
                composed.motion.gesture_amplitude = edit.value
            }
            AvatarStyleDimension::MotionMovementExpressivity => {
                composed.motion.movement_expressivity = edit.value;
            }
            AvatarStyleDimension::MotionTransitionSmoothness => {
                composed.motion.transition_smoothness = edit.value;
            }
            AvatarStyleDimension::MotionIdleMotionIntensity => {
                composed.motion.idle_motion_intensity = edit.value;
            }
            AvatarStyleDimension::MotionLocomotionStylization => {
                composed.motion.locomotion_stylization = edit.value;
            }
            AvatarStyleDimension::ExpressionFacialExpressivity => {
                composed.expression.facial_expressivity = edit.value;
            }
            AvatarStyleDimension::ExpressionGazeExpressivity => {
                composed.expression.gaze_expressivity = edit.value;
            }
            AvatarStyleDimension::ExpressionBlinkIntensity => {
                composed.expression.blink_intensity = edit.value;
            }
            AvatarStyleDimension::ExpressionVisemeIntensity => {
                composed.expression.viseme_intensity = edit.value;
            }
        }
        previous_dimension = Some(tag);
    }

    if let Some(parameters) = &plan.visual_parameters {
        composed.visual.parameters = parameters.clone();
    }
    if let Some(accessibility) = &plan.accessibility {
        // Accessibility restrictions are monotone: composition may add an accommodation
        // but does not silently remove one inherited from a parent style.
        composed.accessibility.reduced_motion |= accessibility.reduced_motion;
        composed.accessibility.high_contrast |= accessibility.high_contrast;
        composed.accessibility.colour_independent_cues |= accessibility.colour_independent_cues;
        composed.accessibility.low_distraction |= accessibility.low_distraction;
        composed.accessibility.low_detail |= accessibility.low_detail;
    }
    let mut required_features = std::collections::BTreeSet::new();
    let mut optional_features = std::collections::BTreeSet::new();
    for (parent, _) in &weighted_parents {
        required_features.extend(parent.required_renderer_features.iter().cloned());
        optional_features.extend(parent.optional_renderer_features.iter().cloned());
    }
    if let Some(features) = &plan.required_renderer_features {
        required_features.extend(features.iter().cloned());
    }
    if let Some(features) = &plan.optional_renderer_features {
        optional_features.extend(features.iter().cloned());
    }
    for feature in &required_features {
        optional_features.remove(feature);
    }
    composed.required_renderer_features = required_features.into_iter().collect();
    composed.optional_renderer_features = optional_features.into_iter().collect();
    composed.validate()?;
    Ok(composed)
}

impl AvatarStyleRendererManifest {
    pub fn validate(&self) -> Result<(), AvatarStyleContractError> {
        if self.schema_version != AVATAR_STYLE_RENDERER_MANIFEST_SCHEMA_VERSION {
            return Err(AvatarStyleContractError::UnsupportedRendererManifestSchema);
        }
        valid_identifier(&self.renderer_id, "renderer_id")?;
        valid_identifier(&self.renderer_version, "renderer_version")?;
        validate_sorted_ids(
            &self.supported_features,
            MAX_AVATAR_STYLE_FEATURES,
            "renderer.supported_features",
        )
    }

    pub fn canonical_digest_blake3(&self) -> Result<String, AvatarStyleContractError> {
        self.validate()?;
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symtropy-avatar-style-renderer-manifest-v1");
        hasher.update(&self.schema_version.to_le_bytes());
        hash_string(&mut hasher, &self.renderer_id);
        hash_string(&mut hasher, &self.renderer_version);
        hasher.update(&(self.supported_features.len() as u64).to_le_bytes());
        for feature in &self.supported_features {
            hash_string(&mut hasher, feature);
        }
        Ok(hasher.finalize().to_hex().to_string())
    }
}

impl AvatarStyleCompatibilityReport {
    pub fn canonical_digest_blake3(&self) -> String {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symtropy-avatar-style-compatibility-report-v1");
        hasher.update(&self.schema_version.to_le_bytes());
        for value in [
            self.profile_id.as_str(),
            self.profile_digest_blake3.as_str(),
            self.renderer_id.as_str(),
            self.renderer_version.as_str(),
            self.renderer_manifest_digest_blake3.as_str(),
        ] {
            hash_string(&mut hasher, value);
        }
        hasher.update(&[match self.status {
            AvatarStyleCompatibilityStatus::Ready => 0,
            AvatarStyleCompatibilityStatus::Degraded => 1,
            AvatarStyleCompatibilityStatus::Unsupported => 2,
        }]);
        for list in [
            self.satisfied_required_features.as_slice(),
            self.missing_required_features.as_slice(),
            self.satisfied_optional_features.as_slice(),
            self.missing_optional_features.as_slice(),
        ] {
            hasher.update(&(list.len() as u64).to_le_bytes());
            for feature in list {
                hash_string(&mut hasher, feature);
            }
        }
        hasher.finalize().to_hex().to_string()
    }
}

/// Evaluates only declared renderer capability. Missing required capabilities return an
/// Unsupported report; missing optional capabilities return Degraded. No rendering occurs.
pub fn evaluate_avatar_style_compatibility(
    profile: &AvatarStyleProfile,
    renderer: &AvatarStyleRendererManifest,
) -> Result<AvatarStyleCompatibilityReport, AvatarStyleContractError> {
    profile.validate()?;
    let renderer_digest = renderer.canonical_digest_blake3()?;
    let profile_digest = profile.canonical_digest_blake3()?;
    let satisfied_required_features = profile
        .required_renderer_features
        .iter()
        .filter(|feature| renderer.supported_features.binary_search(feature).is_ok())
        .cloned()
        .collect::<Vec<_>>();
    let missing_required_features = profile
        .required_renderer_features
        .iter()
        .filter(|feature| renderer.supported_features.binary_search(feature).is_err())
        .cloned()
        .collect::<Vec<_>>();
    let satisfied_optional_features = profile
        .optional_renderer_features
        .iter()
        .filter(|feature| renderer.supported_features.binary_search(feature).is_ok())
        .cloned()
        .collect::<Vec<_>>();
    let missing_optional_features = profile
        .optional_renderer_features
        .iter()
        .filter(|feature| renderer.supported_features.binary_search(feature).is_err())
        .cloned()
        .collect::<Vec<_>>();
    let status = if !missing_required_features.is_empty() {
        AvatarStyleCompatibilityStatus::Unsupported
    } else if !missing_optional_features.is_empty() {
        AvatarStyleCompatibilityStatus::Degraded
    } else {
        AvatarStyleCompatibilityStatus::Ready
    };
    let mut report = AvatarStyleCompatibilityReport {
        schema_version: AVATAR_STYLE_RENDERER_MANIFEST_SCHEMA_VERSION,
        profile_id: profile.profile_id.clone(),
        profile_digest_blake3: profile_digest,
        renderer_id: renderer.renderer_id.clone(),
        renderer_version: renderer.renderer_version.clone(),
        renderer_manifest_digest_blake3: renderer_digest,
        status,
        satisfied_required_features,
        missing_required_features,
        satisfied_optional_features,
        missing_optional_features,
        canonical_digest_blake3: String::new(),
    };
    report.canonical_digest_blake3 = report.canonical_digest_blake3();
    Ok(report)
}

impl AvatarStyleProposal {
    fn validate_content(&self) -> Result<(), AvatarStyleContractError> {
        if self.schema_version != AVATAR_STYLE_PROPOSAL_SCHEMA_VERSION {
            return Err(AvatarStyleContractError::UnsupportedProposalSchema);
        }
        self.profile.validate()?;
        for (value, field) in [
            (self.proposal_id.as_str(), "proposal_id"),
            (self.proposer_ref.as_str(), "proposer_ref"),
            (self.presenter_ref.as_str(), "presenter_ref"),
        ] {
            valid_identifier(value, field)?;
        }
        if self.profile.identity_ref != self.presenter_ref {
            return Err(AvatarStyleContractError::IdentityBindingMismatch);
        }
        if self.rationale.trim().is_empty()
            || self.rationale.len() > MAX_AVATAR_STYLE_RATIONALE_BYTES
            || self.rationale.chars().any(char::is_control)
        {
            return Err(AvatarStyleContractError::InvalidStyleValue("rationale"));
        }
        match (self.scope, self.human_partner_ref.as_deref()) {
            (PresentationScope::SharedRelationalScene, Some(partner_ref)) => {
                valid_identifier(partner_ref, "human_partner_ref")?;
                if partner_ref == self.presenter_ref {
                    return Err(AvatarStyleContractError::InvalidProposalScope(
                        "presenter and human partner must be distinct participants",
                    ));
                }
            }
            (PresentationScope::SharedRelationalScene, None) => {
                return Err(AvatarStyleContractError::InvalidProposalScope(
                    "shared relational scene requires an explicit human partner reference",
                ));
            }
            (_, Some(partner_ref)) => {
                valid_identifier(partner_ref, "human_partner_ref")?;
                if partner_ref == self.presenter_ref {
                    return Err(AvatarStyleContractError::InvalidProposalScope(
                        "presenter and human partner must be distinct participants",
                    ));
                }
            }
            (_, None) => {}
        }
        match self.origin {
            StyleProposalOrigin::SymthaeaSelfAuthored
                if self.proposer_ref != self.presenter_ref =>
            {
                return Err(AvatarStyleContractError::InvalidProposalScope(
                    "self-authored proposal must identify the presenter as proposer",
                ));
            }
            StyleProposalOrigin::HumanPartnerSuggested
                if self.human_partner_ref.as_deref() != Some(self.proposer_ref.as_str()) =>
            {
                return Err(AvatarStyleContractError::InvalidProposalScope(
                    "partner-suggested proposal must identify the declared partner as proposer",
                ));
            }
            StyleProposalOrigin::JointCoCreation if self.human_partner_ref.is_none() => {
                return Err(AvatarStyleContractError::InvalidProposalScope(
                    "joint co-creation requires a declared human partner",
                ));
            }
            _ => {}
        }
        Ok(())
    }

    fn content_digest_unchecked(&self) -> Result<String, AvatarStyleContractError> {
        let profile_digest = self.profile.canonical_digest_blake3()?;
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symtropy-avatar-style-proposal-content-v1");
        hasher.update(&self.schema_version.to_le_bytes());
        for value in [
            self.proposal_id.as_str(),
            self.proposer_ref.as_str(),
            self.presenter_ref.as_str(),
            self.rationale.as_str(),
            profile_digest.as_str(),
        ] {
            hash_string(&mut hasher, value);
        }
        hasher.update(&[origin_tag(self.origin), scope_tag(self.scope)]);
        match self.human_partner_ref.as_deref() {
            Some(value) => {
                hasher.update(&[1]);
                hash_string(&mut hasher, value);
            }
            None => {
                hasher.update(&[0]);
            }
        }
        Ok(hasher.finalize().to_hex().to_string())
    }

    /// Stable content identity that an approval must explicitly acknowledge.
    /// It excludes the append-only approval ledger, avoiding a circular digest.
    pub fn canonical_content_digest_blake3(&self) -> Result<String, AvatarStyleContractError> {
        self.validate_content()?;
        self.content_digest_unchecked()
    }

    pub fn validate(&self) -> Result<(), AvatarStyleContractError> {
        self.validate_content()?;
        if self.approvals.len() > MAX_AVATAR_STYLE_APPROVALS {
            return Err(AvatarStyleContractError::ResourceLimitExceeded("approvals"));
        }
        let content_digest = self.content_digest_unchecked()?;
        let mut previous_sequence = None;
        for approval in &self.approvals {
            valid_identifier(&approval.party_ref, "approval.party_ref")?;
            valid_digest(
                &approval.approved_content_digest_sha256,
                "approval.approved_content_digest_sha256",
            )?;
            valid_digest(
                &approval.consent_receipt_sha256,
                "approval.consent_receipt_sha256",
            )?;
            if approval.approved_content_digest_sha256 != content_digest {
                return Err(AvatarStyleContractError::InvalidApproval(
                    "approval is bound to different proposal content",
                ));
            }
            if approval.decision_sequence == 0
                || previous_sequence.is_some_and(|previous| previous >= approval.decision_sequence)
            {
                return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                    "approval decision_sequence",
                ));
            }
            previous_sequence = Some(approval.decision_sequence);
            match approval.role {
                StyleApprovalRole::Presenter if approval.party_ref != self.presenter_ref => {
                    return Err(AvatarStyleContractError::InvalidApproval(
                        "presenter approval party_ref must match presenter_ref",
                    ));
                }
                StyleApprovalRole::HumanPartner => {
                    if self.human_partner_ref.as_deref() != Some(approval.party_ref.as_str()) {
                        return Err(AvatarStyleContractError::InvalidApproval(
                            "partner approval party_ref must match the declared human_partner_ref",
                        ));
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }

    /// The presenter always controls their own presentation. Shared relational scenes
    /// additionally require the human partner's latest decision to be Accepted.
    pub fn is_activatable(&self) -> Result<bool, AvatarStyleContractError> {
        self.validate()?;
        let required_roles: &[StyleApprovalRole] = match self.scope {
            PresentationScope::SelfPresentation | PresentationScope::PublicScene => {
                &[StyleApprovalRole::Presenter]
            }
            PresentationScope::SharedRelationalScene => &[
                StyleApprovalRole::Presenter,
                StyleApprovalRole::HumanPartner,
            ],
        };
        for role in required_roles {
            let latest = self
                .approvals
                .iter()
                .filter(|item| item.role == *role)
                .max_by_key(|item| item.decision_sequence);
            let Some(approval) = latest else {
                return Ok(false);
            };
            if approval.decision != StyleApprovalDecision::Accepted {
                return Ok(false);
            }
        }
        Ok(true)
    }

    pub fn canonical_digest_blake3(&self) -> Result<String, AvatarStyleContractError> {
        self.validate()?;
        let content_digest = self.content_digest_unchecked()?;
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symtropy-avatar-style-proposal-v1");
        hash_string(&mut hasher, &content_digest);
        hasher.update(&(self.approvals.len() as u64).to_le_bytes());
        for approval in &self.approvals {
            hash_string(&mut hasher, &approval.party_ref);
            hash_string(&mut hasher, &approval.approved_content_digest_sha256);
            hash_string(&mut hasher, &approval.consent_receipt_sha256);
            hasher.update(&[
                approval_role_tag(approval.role),
                approval_decision_tag(approval.decision),
            ]);
            hasher.update(&approval.decision_sequence.to_le_bytes());
        }
        Ok(hasher.finalize().to_hex().to_string())
    }
}

