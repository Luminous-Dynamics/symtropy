pub const AVATAR_STYLE_PROPOSAL_SCHEMA_VERSION: u32 = 1;
pub const AVATAR_STYLE_RENDERER_MANIFEST_SCHEMA_VERSION: u32 = 1;
pub const MAX_AVATAR_STYLE_PARAMETERS: usize = 64;
pub const MAX_AVATAR_STYLE_PARENT_PROFILES: usize = 8;
pub const MAX_AVATAR_STYLE_FEATURES: usize = 64;
pub const MAX_AVATAR_STYLE_APPROVALS: usize = 16;
pub const MAX_AVATAR_STYLE_ID_BYTES: usize = 128;
pub const MAX_AVATAR_STYLE_RATIONALE_BYTES: usize = 1_024;
const DIGEST_HEX_BYTES: usize = 64;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PresentationScope {
    /// Only the avatar presenter is represented by this profile.
    SelfPresentation,
    /// The presentation explicitly represents both participants.
    SharedRelationalScene,
    /// The presenter's avatar is shown in a public or shared environment.
    PublicScene,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum StyleProposalOrigin {
    /// Generated by Symthaea as a candidate for her own presentation.
    SymthaeaSelfAuthored,
    /// Suggested by the human partner; it is not automatically accepted.
    HumanPartnerSuggested,
    /// Explicitly developed through a joint co-design process.
    JointCoCreation,
    /// Selected from a curated template library.
    CuratedTemplate,
    /// Generated by a bounded style-grammar mutation or search process.
    AutomatedMutation,
}

