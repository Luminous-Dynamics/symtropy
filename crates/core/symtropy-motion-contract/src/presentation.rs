#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AvatarStyleContractError {
    UnsupportedProfileSchema,
    UnsupportedProposalSchema,
    InvalidIdentifier(&'static str),
    InvalidDigest(&'static str),
    InvalidStyleValue(&'static str),
    UnsortedOrDuplicate(&'static str),
    ResourceLimitExceeded(&'static str),
    InvalidProposalScope(&'static str),
    InvalidApproval(&'static str),
    IdentityBindingMismatch,
    ParentIdentityMismatch,
    InvalidCompositionPlan(&'static str),
    UnsupportedRendererManifestSchema,
}

impl fmt::Display for AvatarStyleContractError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedProfileSchema => write!(f, "unsupported avatar style profile schema"),
            Self::UnsupportedProposalSchema => {
                write!(f, "unsupported avatar style proposal schema")
            }
            Self::InvalidIdentifier(field) => write!(f, "invalid avatar style identifier: {field}"),
            Self::InvalidDigest(field) => write!(f, "invalid avatar style digest: {field}"),
            Self::InvalidStyleValue(field) => write!(f, "invalid avatar style value: {field}"),
            Self::UnsortedOrDuplicate(field) => {
                write!(f, "avatar style values must be sorted and unique: {field}")
            }
            Self::ResourceLimitExceeded(field) => {
                write!(f, "avatar style resource limit exceeded: {field}")
            }
            Self::InvalidProposalScope(field) => {
                write!(f, "invalid avatar style proposal scope: {field}")
            }
            Self::InvalidApproval(field) => write!(f, "invalid avatar style approval: {field}"),
            Self::IdentityBindingMismatch => {
                write!(f, "avatar style identity does not match proposal presenter")
            }
            Self::ParentIdentityMismatch => write!(
                f,
                "composed avatar styles do not share the same identity and rig anchors"
            ),
            Self::InvalidCompositionPlan(field) => {
                write!(f, "invalid avatar style composition plan: {field}")
            }
            Self::UnsupportedRendererManifestSchema => {
                write!(f, "unsupported avatar style renderer manifest schema")
            }
        }
    }
}

impl Error for AvatarStyleContractError {}

fn valid_identifier(value: &str, field: &'static str) -> Result<(), AvatarStyleContractError> {
    let trimmed = value.trim();
    if trimmed.is_empty()
        || trimmed.len() > MAX_AVATAR_STYLE_ID_BYTES
        || value != trimmed
        || value.chars().any(char::is_control)
    {
        return Err(AvatarStyleContractError::InvalidIdentifier(field));
    }
    Ok(())
}

fn valid_namespaced_identifier(
    value: &str,
    field: &'static str,
) -> Result<(), AvatarStyleContractError> {
    valid_identifier(value, field)?;
    if !value.contains('.') && !value.contains(':') {
        return Err(AvatarStyleContractError::InvalidIdentifier(field));
    }
    Ok(())
}

fn valid_digest(value: &str, field: &'static str) -> Result<(), AvatarStyleContractError> {
    if value.len() != DIGEST_HEX_BYTES
        || !value.bytes().all(|byte| {
            byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte) || (b'A'..=b'F').contains(&byte)
        })
    {
        return Err(AvatarStyleContractError::InvalidDigest(field));
    }
    Ok(())
}

fn validate_unit_interval(value: f64, field: &'static str) -> Result<(), AvatarStyleContractError> {
    if !value.is_finite() || !(0.0..=1.0).contains(&value) {
        return Err(AvatarStyleContractError::InvalidStyleValue(field));
    }
    Ok(())
}

fn validate_sorted_ids(
    values: &[String],
    limit: usize,
    field: &'static str,
) -> Result<(), AvatarStyleContractError> {
    if values.len() > limit {
        return Err(AvatarStyleContractError::ResourceLimitExceeded(field));
    }
    let mut previous: Option<&str> = None;
    for value in values {
        valid_identifier(value, field)?;
        if previous.is_some_and(|prior| prior >= value.as_str()) {
            return Err(AvatarStyleContractError::UnsortedOrDuplicate(field));
        }
        previous = Some(value);
    }
    Ok(())
}

fn hash_string(hasher: &mut blake3::Hasher, value: &str) {
    hasher.update(&(value.len() as u64).to_le_bytes());
    hasher.update(value.as_bytes());
}

fn hash_f64(hasher: &mut blake3::Hasher, value: f64) {
    hasher.update(&value.to_bits().to_le_bytes());
}

fn scope_tag(value: PresentationScope) -> u8 {
    match value {
        PresentationScope::SelfPresentation => 0,
        PresentationScope::SharedRelationalScene => 1,
        PresentationScope::PublicScene => 2,
    }
}

fn origin_tag(value: StyleProposalOrigin) -> u8 {
    match value {
        StyleProposalOrigin::SymthaeaSelfAuthored => 0,
        StyleProposalOrigin::HumanPartnerSuggested => 1,
        StyleProposalOrigin::JointCoCreation => 2,
        StyleProposalOrigin::CuratedTemplate => 3,
        StyleProposalOrigin::AutomatedMutation => 4,
    }
}

fn approval_role_tag(value: StyleApprovalRole) -> u8 {
    match value {
        StyleApprovalRole::Presenter => 0,
        StyleApprovalRole::HumanPartner => 1,
    }
}

fn approval_decision_tag(value: StyleApprovalDecision) -> u8 {
    match value {
        StyleApprovalDecision::Accepted => 0,
        StyleApprovalDecision::Rejected => 1,
        StyleApprovalDecision::Revoked => 2,
    }
}

impl AvatarStyleProfile {
    pub fn validate(&self) -> Result<(), AvatarStyleContractError> {
        if self.schema_version != AVATAR_STYLE_PROFILE_SCHEMA_VERSION {
            return Err(AvatarStyleContractError::UnsupportedProfileSchema);
        }
        for (value, field) in [
            (self.profile_id.as_str(), "profile_id"),
            (self.identity_ref.as_str(), "identity_ref"),
            (self.context_id.as_str(), "context_id"),
        ] {
            valid_identifier(value, field)?;
        }
        for (value, field) in [
            (self.visual.family_id.as_str(), "visual.family_id"),
            (self.visual.palette_id.as_str(), "visual.palette_id"),
            (
                self.visual.material_language_id.as_str(),
                "visual.material_language_id",
            ),
        ] {
            valid_namespaced_identifier(value, field)?;
        }
        valid_digest(&self.identity_anchor_sha256, "identity_anchor_sha256")?;
        valid_digest(&self.skeleton_signature_sha256, "skeleton_signature_sha256")?;
        validate_sorted_ids(
            &self.parent_profile_ids,
            MAX_AVATAR_STYLE_PARENT_PROFILES,
            "parent_profile_ids",
        )?;
        if self
            .parent_profile_ids
            .iter()
            .any(|parent| parent == &self.profile_id)
        {
            return Err(AvatarStyleContractError::InvalidIdentifier(
                "profile cannot name itself as a parent",
            ));
        }
        for (value, field) in [
            (self.visual.realism, "visual.realism"),
            (self.visual.stylization, "visual.stylization"),
            (self.visual.detail_density, "visual.detail_density"),
            (self.visual.ornamentation, "visual.ornamentation"),
            (
                self.visual.silhouette_expressivity,
                "visual.silhouette_expressivity",
            ),
            (self.motion.gesture_amplitude, "motion.gesture_amplitude"),
            (
                self.motion.movement_expressivity,
                "motion.movement_expressivity",
            ),
            (
                self.motion.transition_smoothness,
                "motion.transition_smoothness",
            ),
            (
                self.motion.idle_motion_intensity,
                "motion.idle_motion_intensity",
            ),
            (
                self.motion.locomotion_stylization,
                "motion.locomotion_stylization",
            ),
            (
                self.expression.facial_expressivity,
                "expression.facial_expressivity",
            ),
            (
                self.expression.gaze_expressivity,
                "expression.gaze_expressivity",
            ),
            (
                self.expression.blink_intensity,
                "expression.blink_intensity",
            ),
            (
                self.expression.viseme_intensity,
                "expression.viseme_intensity",
            ),
        ] {
            validate_unit_interval(value, field)?;
        }
        if self.visual.parameters.len() > MAX_AVATAR_STYLE_PARAMETERS {
            return Err(AvatarStyleContractError::ResourceLimitExceeded(
                "visual.parameters",
            ));
        }
        let mut previous_parameter: Option<&str> = None;
        for parameter in &self.visual.parameters {
            valid_namespaced_identifier(&parameter.parameter_id, "visual.parameter_id")?;
            if previous_parameter.is_some_and(|prior| prior >= parameter.parameter_id.as_str()) {
                return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                    "visual.parameters",
                ));
            }
            validate_unit_interval(parameter.value, "visual.parameter.value")?;
            previous_parameter = Some(&parameter.parameter_id);
        }
        validate_sorted_ids(
            &self.required_renderer_features,
            MAX_AVATAR_STYLE_FEATURES,
            "required_renderer_features",
        )?;
        validate_sorted_ids(
            &self.optional_renderer_features,
            MAX_AVATAR_STYLE_FEATURES,
            "optional_renderer_features",
        )?;
        for feature in &self.required_renderer_features {
            if self
                .optional_renderer_features
                .binary_search(feature)
                .is_ok()
            {
                return Err(AvatarStyleContractError::UnsortedOrDuplicate(
                    "renderer feature cannot be both required and optional",
                ));
            }
        }
        Ok(())
    }

    /// Deterministic profile identity. This commits to parameters and identity/rig anchors;
    /// it does not imply that the style has been approved.
    pub fn canonical_digest_blake3(&self) -> Result<String, AvatarStyleContractError> {
        self.validate()?;
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symtropy-avatar-style-profile-v1");
        hasher.update(&self.schema_version.to_le_bytes());
        for value in [
            self.profile_id.as_str(),
            self.identity_ref.as_str(),
            self.identity_anchor_sha256.as_str(),
            self.skeleton_signature_sha256.as_str(),
            self.context_id.as_str(),
            self.visual.family_id.as_str(),
            self.visual.palette_id.as_str(),
            self.visual.material_language_id.as_str(),
        ] {
            hash_string(&mut hasher, value);
        }
        hasher.update(&(self.parent_profile_ids.len() as u64).to_le_bytes());
        for value in &self.parent_profile_ids {
            hash_string(&mut hasher, value);
        }
        for value in [
            self.visual.realism,
            self.visual.stylization,
            self.visual.detail_density,
            self.visual.ornamentation,
            self.visual.silhouette_expressivity,
            self.motion.gesture_amplitude,
            self.motion.movement_expressivity,
            self.motion.transition_smoothness,
            self.motion.idle_motion_intensity,
            self.motion.locomotion_stylization,
            self.expression.facial_expressivity,
            self.expression.gaze_expressivity,
            self.expression.blink_intensity,
            self.expression.viseme_intensity,
        ] {
            hash_f64(&mut hasher, value);
        }
        hasher.update(&(self.visual.parameters.len() as u64).to_le_bytes());
        for parameter in &self.visual.parameters {
            hash_string(&mut hasher, &parameter.parameter_id);
            hash_f64(&mut hasher, parameter.value);
        }
        hasher.update(&[
            u8::from(self.accessibility.reduced_motion),
            u8::from(self.accessibility.high_contrast),
            u8::from(self.accessibility.colour_independent_cues),
            u8::from(self.accessibility.low_distraction),
            u8::from(self.accessibility.low_detail),
        ]);
        for list in [
            self.required_renderer_features.as_slice(),
            self.optional_renderer_features.as_slice(),
        ] {
            hasher.update(&(list.len() as u64).to_le_bytes());
            for value in list {
                hash_string(&mut hasher, value);
            }
        }
        Ok(hasher.finalize().to_hex().to_string())
    }
}

