//! Renderer-independent avatar presentation styles and consent-bound proposals.
//!
//! Presentation is deliberately separate from semantic motion intent, physical skills,
//! facial-event provenance, and renderer implementation. A style profile can influence
//! how an already-authorized or observed action is presented; it cannot create an action,
//! claim an internal emotion, or override physical and safety constraints.

use serde::{Deserialize, Serialize};
use std::{error::Error, fmt};

