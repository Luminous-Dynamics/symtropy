//! External frozen-vector oracle for V1 canonical population-state identity.
//!
//! This test intentionally uses only the public `symtropy-lifesim-core` API and
//! a literal byte vector. It must not reconstruct expected bytes with the
//! product encoder's private helpers; otherwise implementation and oracle could
//! drift together without changing the manifest version.

use std::collections::BTreeMap;

use symtropy_lifesim_core::population::{
    CountDistribution, PopulationAgeBand, PopulationCell, PopulationConditionBand, PopulationState,
};
use symtropy_lifesim_core::population_manifest::{
    ManifestBoundPopulationState, POPULATION_STATE_MANIFEST_VERSION,
};

const EXPECTED_V1: &[u8; 160] = &[
    0x53, 0x59, 0x4d, 0x54, 0x52, 0x4f, 0x50, 0x59, 0x5f, 0x50, 0x4f, 0x50, 0x55, 0x4c, 0x41, 0x54,
    0x49, 0x4f, 0x4e, 0x5f, 0x53, 0x54, 0x41, 0x54, 0x45, 0x5f, 0x4d, 0x41, 0x4e, 0x49, 0x46, 0x45,
    0x53, 0x54, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0a, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0xa0, 0x25, 0x26, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x01, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0x07, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x04, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x08, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05,
    0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
    0xfe, 0xff, 0xff, 0xff, 0x03, 0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
];

fn population() -> PopulationState {
    PopulationState::new(
        10,
        2_500_000,
        CountDistribution::new(BTreeMap::from([
            (PopulationAgeBand::Juvenile, 3),
            (PopulationAgeBand::Mature, 7),
        ]))
        .unwrap(),
        CountDistribution::new(BTreeMap::from([
            (PopulationConditionBand::Stable, 8),
            (PopulationConditionBand::Stressed, 2),
        ]))
        .unwrap(),
        CountDistribution::new(BTreeMap::from([
            (PopulationCell::new(0, 0, 0), 4),
            (PopulationCell::new(1, -2, 3), 6),
        ]))
        .unwrap(),
    )
    .unwrap()
}

#[test]
fn v1_exact_population_state_manifest_is_frozen() {
    let population = population();
    let bound = ManifestBoundPopulationState::new(&population).unwrap();
    let manifest = bound.manifest();

    assert_eq!(POPULATION_STATE_MANIFEST_VERSION, 1);
    assert_eq!(manifest.version(), 1);
    assert_eq!(manifest.as_bytes().len(), EXPECTED_V1.len());
    assert_eq!(manifest.as_bytes(), EXPECTED_V1);
}
