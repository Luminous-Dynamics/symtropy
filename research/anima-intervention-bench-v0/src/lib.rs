//! Leakage-resistant model discrimination and intervention-selection primitives.
//!
//! This crate is intentionally standalone and dependency-free. It provides
//! benchmark mechanics, not a biological model or an empirical result.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;

const NORMAL_90: f64 = 1.644_853_626_951_472_2;
const LOG_SQRT_2PI: f64 = 0.918_938_533_204_672_7;
const SPLITMIX_GAMMA: u64 = 0x9e37_79b9_7f4a_7c15;

/// Origin class of an observation or reference outcome.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum EvidenceClass {
    PeerReviewedMeasured,
    PreprintMeasured,
    InSilicoGenerated,
    SyntheticFixture,
}

/// Strength of claim permitted by the supplied observation provenance.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EvidenceClaim {
    /// Software-contract tests whose outcomes are generated by the harness.
    SyntheticHarness,
    /// A model demonstration using generated or synthetic outcomes only.
    InSilicoDemonstration,
    /// A reproduction against a source explicitly classified as a preprint.
    PreprintReproduction,
    /// Replication against peer-reviewed measured outcomes.
    PeerReviewedReplication,
    /// Generalization across at least two independently identified connectome
    /// datasets and at least two individuals, using peer-reviewed measurements.
    CrossDatasetGeneralization,
}

/// One observed trial/event. A v0 benchmark run is for one versioned metric and
/// one physical unit; do not pool unlike endpoints into one score.
#[derive(Debug, Clone, PartialEq)]
pub struct TrialObservation {
    pub sample_id: String,
    pub individual_id: String,
    pub connectome_dataset_id: String,
    pub intervention_family_id: String,
    pub condition_id: String,
    pub metric_id: String,
    pub unit_id: String,
    pub evidence_class: EvidenceClass,
    pub observed_value: f64,
}

/// Explicit group holdouts. This is a deterministic split: it never randomly
/// sends individual timesteps from one group into both partitions.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SplitPolicy {
    pub held_out_intervention_families: BTreeSet<String>,
    pub held_out_conditions: BTreeSet<String>,
    pub held_out_individuals: BTreeSet<String>,
    pub held_out_connectome_datasets: BTreeSet<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum HoldoutReason {
    InterventionFamily,
    Condition,
    Individual,
    ConnectomeDataset,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Partition {
    Training,
    HeldOut,
}

/// Indices refer to the exact input slice and are stable for that run only.
/// Persist sample IDs and the policy in a run receipt; never persist indices as
/// if they were durable identities.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TrialSplit {
    pub training_indices: Vec<usize>,
    pub held_out_indices: Vec<usize>,
    pub held_out_reasons: BTreeMap<String, Vec<HoldoutReason>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BenchError {
    EmptyDataset,
    EmptyIdentifier { field: &'static str },
    EmptyOutcomeMetric,
    InvalidObservedValue { sample_id: String },
    DuplicateSampleId(String),
    EmptyHoldoutPolicy,
    InvalidHoldoutIdentifier { field: &'static str },
    UnobservedHoldoutGroup { field: &'static str, value: String },
    EmptyTrainingPartition,
    EmptyHeldOutPartition,
    EvidenceClaimNotSupported { claim: EvidenceClaim },
    DuplicatePrediction { model_id: String, sample_id: String },
    MissingPrediction { model_id: String, sample_id: String },
    UnexpectedPrediction { model_id: String, sample_id: String },
    PredictionModelMismatch { expected: String, actual: String },
    PredictionSchemaMismatch { sample_id: String },
    InvalidPrediction { sample_id: String },
    InvalidBootstrapSamples,
    DuplicateInterventionId(String),
    InvalidInterventionCost { intervention_id: String },
    InvalidMonteCarloSamples,
    TooFewModelFamilies,
    ModelFamilySetMismatch { intervention_id: String },
    InvalidModelDistribution { intervention_id: String, model_id: String },
    InconsistentOutcomeSchema { intervention_id: String },
}

impl fmt::Display for BenchError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyDataset => write!(f, "trial dataset is empty"),
            Self::EmptyIdentifier { field } => write!(f, "empty identifier: {field}"),
            Self::EmptyOutcomeMetric => write!(f, "outcome metric and unit identifiers must be non-empty"),
            Self::InvalidObservedValue { sample_id } => write!(f, "observed value is non-finite for sample {sample_id}"),
            Self::DuplicateSampleId(id) => write!(f, "duplicate sample identity: {id}"),
            Self::EmptyHoldoutPolicy => write!(f, "at least one explicit group holdout is required"),
            Self::InvalidHoldoutIdentifier { field } => write!(f, "empty identifier in holdout set: {field}"),
            Self::UnobservedHoldoutGroup { field, value } => write!(f, "holdout group was not present in observations: {field}={value}"),
            Self::EmptyTrainingPartition => write!(f, "split produced no training observations"),
            Self::EmptyHeldOutPartition => write!(f, "split produced no held-out observations"),
            Self::EvidenceClaimNotSupported { claim } => write!(f, "observation provenance does not support claim {claim:?}"),
            Self::DuplicatePrediction { model_id, sample_id } => write!(f, "duplicate prediction for model {model_id}, sample {sample_id}"),
            Self::MissingPrediction { model_id, sample_id } => write!(f, "missing prediction for model {model_id}, sample {sample_id}"),
            Self::UnexpectedPrediction { model_id, sample_id } => write!(f, "prediction for model {model_id} references unknown sample {sample_id}"),
            Self::PredictionModelMismatch { expected, actual } => write!(f, "prediction model mismatch: expected {expected}, got {actual}"),
            Self::PredictionSchemaMismatch { sample_id } => write!(f, "metric/unit mismatch for sample {sample_id}"),
            Self::InvalidPrediction { sample_id } => write!(f, "invalid prediction mean or standard deviation for sample {sample_id}"),
            Self::InvalidBootstrapSamples => write!(f, "cluster bootstrap requires at least 100 resamples"),
            Self::DuplicateInterventionId(id) => write!(f, "duplicate intervention candidate id: {id}"),
            Self::InvalidInterventionCost { intervention_id } => write!(f, "invalid positive finite intervention cost: {intervention_id}"),
            Self::InvalidMonteCarloSamples => write!(f, "expected-information-gain estimation requires at least 100 samples per model"),
            Self::TooFewModelFamilies => write!(f, "at least two competing model families are required"),
            Self::ModelFamilySetMismatch { intervention_id } => write!(f, "model-family set differs across intervention candidates: {intervention_id}"),
            Self::InvalidModelDistribution { intervention_id, model_id } => write!(f, "invalid Gaussian prediction for model {model_id} under intervention {intervention_id}"),
            Self::InconsistentOutcomeSchema { intervention_id } => write!(f, "intervention candidates do not share one metric/unit schema: {intervention_id}"),
        }
    }
}

impl std::error::Error for BenchError {}

fn non_empty(value: &str, field: &'static str) -> Result<(), BenchError> {
    if value.trim().is_empty() {
        Err(BenchError::EmptyIdentifier { field })
    } else {
        Ok(())
    }
}

fn validate_observations(observations: &[TrialObservation]) -> Result<(), BenchError> {
    if observations.is_empty() {
        return Err(BenchError::EmptyDataset);
    }
    let mut sample_ids = BTreeSet::new();
    for row in observations {
        non_empty(&row.sample_id, "sample_id")?;
        non_empty(&row.individual_id, "individual_id")?;
        non_empty(&row.connectome_dataset_id, "connectome_dataset_id")?;
        non_empty(&row.intervention_family_id, "intervention_family_id")?;
        non_empty(&row.condition_id, "condition_id")?;
        non_empty(&row.metric_id, "metric_id")?;
        non_empty(&row.unit_id, "unit_id")?;
        if !row.observed_value.is_finite() {
            return Err(BenchError::InvalidObservedValue {
                sample_id: row.sample_id.clone(),
            });
        }
        if !sample_ids.insert(row.sample_id.as_str()) {
            return Err(BenchError::DuplicateSampleId(row.sample_id.clone()));
        }
    }
    let schema = (&observations[0].metric_id, &observations[0].unit_id);
    if observations
        .iter()
        .any(|row| (&row.metric_id, &row.unit_id) != schema)
    {
        return Err(BenchError::EmptyOutcomeMetric);
    }
    Ok(())
}

/// Assign all members of explicitly held-out groups to the test partition.
/// Rows matching more than one held-out dimension retain every reason.
pub fn build_group_held_out_split(
    observations: &[TrialObservation],
    policy: &SplitPolicy,
) -> Result<TrialSplit, BenchError> {
    validate_observations(observations)?;
    if policy.held_out_intervention_families.is_empty()
        && policy.held_out_conditions.is_empty()
        && policy.held_out_individuals.is_empty()
        && policy.held_out_connectome_datasets.is_empty()
    {
        return Err(BenchError::EmptyHoldoutPolicy);
    }

    for id in &policy.held_out_intervention_families {
        non_empty(id, "held_out_intervention_family")?;
    }
    for id in &policy.held_out_conditions {
        non_empty(id, "held_out_condition")?;
    }
    for id in &policy.held_out_individuals {
        non_empty(id, "held_out_individual")?;
    }
    for id in &policy.held_out_connectome_datasets {
        non_empty(id, "held_out_connectome_dataset")?;
    }

    let observed_interventions: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.intervention_family_id.as_str())
        .collect();
    let observed_conditions: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.condition_id.as_str())
        .collect();
    let observed_individuals: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.individual_id.as_str())
        .collect();
    let observed_datasets: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.connectome_dataset_id.as_str())
        .collect();

    for id in &policy.held_out_intervention_families {
        if !observed_interventions.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "intervention_family",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_conditions {
        if !observed_conditions.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "condition",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_individuals {
        if !observed_individuals.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "individual",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_connectome_datasets {
        if !observed_datasets.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "connectome_dataset",
                value: id.clone(),
            });
        }
    }

    let mut split = TrialSplit {
        training_indices: Vec::new(),
        held_out_indices: Vec::new(),
        held_out_reasons: BTreeMap::new(),
    };
    for (index, row) in observations.iter().enumerate() {
        let mut reasons = Vec::new();
        if policy
            .held_out_intervention_families
            .contains(&row.intervention_family_id)
        {
            reasons.push(HoldoutReason::InterventionFamily);
        }
        if policy.held_out_conditions.contains(&row.condition_id) {
            reasons.push(HoldoutReason::Condition);
        }
        if policy.held_out_individuals.contains(&row.individual_id) {
            reasons.push(HoldoutReason::Individual);
        }
        if policy
            .held_out_connectome_datasets
            .contains(&row.connectome_dataset_id)
        {
            reasons.push(HoldoutReason::ConnectomeDataset);
        }

        if reasons.is_empty() {
            split.training_indices.push(index);
        } else {
            split.held_out_indices.push(index);
            split
                .held_out_reasons
                .insert(row.sample_id.clone(), reasons);
        }
    }

    if split.training_indices.is_empty() {
        return Err(BenchError::EmptyTrainingPartition);
    }
    if split.held_out_indices.is_empty() {
        return Err(BenchError::EmptyHeldOutPartition);
    }

    // Defensive postcondition: no training row may match any held-out group.
    for index in &split.training_indices {
        let row = &observations[*index];
        if policy.held_out_intervention_families.contains(&row.intervention_family_id)
            || policy.held_out_conditions.contains(&row.condition_id)
            || policy.held_out_individuals.contains(&row.individual_id)
            || policy
                .held_out_connectome_datasets
                .contains(&row.connectome_dataset_id)
        {
            return Err(BenchError::EmptyTrainingPartition);
        }
    }
    Ok(split)
}

/// Enforce the maximum scientific claim permitted by the supplied provenance.
/// Synthetic and in-silico rows can never be promoted to empirical replication.
pub fn validate_evidence_claim(
    observations: &[TrialObservation],
    claim: EvidenceClaim,
) -> Result<(), BenchError> {
    validate_observations(observations)?;
    let classes: BTreeSet<EvidenceClass> =
        observations.iter().map(|row| row.evidence_class).collect();

    let accepted = match claim {
        EvidenceClaim::SyntheticHarness => {
            classes == BTreeSet::from([EvidenceClass::SyntheticFixture])
        }
        EvidenceClaim::InSilicoDemonstration => {
            classes.iter().all(|class| {
                matches!(
                    class,
                    EvidenceClass::InSilicoGenerated | EvidenceClass::SyntheticFixture
                )
            }) && classes.contains(&EvidenceClass::InSilicoGenerated)
        }
        EvidenceClaim::PreprintReproduction => {
            classes.iter().all(|class| {
                matches!(
                    class,
                    EvidenceClass::PreprintMeasured | EvidenceClass::PeerReviewedMeasured
                )
            }) && classes.contains(&EvidenceClass::PreprintMeasured)
        }
        EvidenceClaim::PeerReviewedReplication => {
            classes == BTreeSet::from([EvidenceClass::PeerReviewedMeasured])
        }
        EvidenceClaim::CrossDatasetGeneralization => {
            classes == BTreeSet::from([EvidenceClass::PeerReviewedMeasured])
                && observations
                    .iter()
                    .map(|row| row.connectome_dataset_id.as_str())
                    .collect::<BTreeSet<_>>()
                    .len()
                    >= 2
                && observations
                    .iter()
                    .map(|row| row.individual_id.as_str())
                    .collect::<BTreeSet<_>>()
                    .len()
                    >= 2
        }
    };

    if accepted {
        Ok(())
    } else {
        Err(BenchError::EvidenceClaimNotSupported { claim })
    }
}

/// One scalar Gaussian prediction for one sample from one model family.
#[derive(Debug, Clone, PartialEq)]
pub struct TrialPrediction {
    pub model_family_id: String,
    pub sample_id: String,
    pub mean: f64,
    pub standard_deviation: f64,
}

#[derive(Debug, Clone, PartialEq)]
pub struct PredictionScore {
    pub model_family_id: String,
    pub trial_count: usize,
    pub rmse: f64,
    /// Mean per-trial Gaussian log predictive density; larger is better.
    pub mean_log_predictive_density: f64,
    /// Empirical coverage of the Gaussian central 90% predictive interval.
    pub coverage_90: f64,
}

fn gaussian_log_density(value: f64, mean: f64, standard_deviation: f64) -> f64 {
    let z = (value - mean) / standard_deviation;
    -LOG_SQRT_2PI - standard_deviation.ln() - 0.5 * z * z
}

fn validate_prediction_join<'a>(
    model_family_id: &str,
    predictions: &'a [TrialPrediction],
    observations: &[TrialObservation],
) -> Result<BTreeMap<&'a str, &'a TrialPrediction>, BenchError> {
    validate_observations(observations)?;
    non_empty(model_family_id, "model_family_id")?;
    let known_samples: BTreeSet<&str> =
        observations.iter().map(|row| row.sample_id.as_str()).collect();
    let mut by_sample = BTreeMap::new();

    for prediction in predictions {
        if prediction.model_family_id != model_family_id {
            return Err(BenchError::PredictionModelMismatch {
                expected: model_family_id.to_string(),
                actual: prediction.model_family_id.clone(),
            });
        }
        non_empty(&prediction.sample_id, "prediction.sample_id")?;
        if !known_samples.contains(prediction.sample_id.as_str()) {
            return Err(BenchError::UnexpectedPrediction {
                model_id: model_family_id.to_string(),
                sample_id: prediction.sample_id.clone(),
            });
        }
        if !prediction.mean.is_finite()
            || !prediction.standard_deviation.is_finite()
            || prediction.standard_deviation <= 0.0
        {
            return Err(BenchError::InvalidPrediction {
                sample_id: prediction.sample_id.clone(),
            });
        }
        if by_sample
            .insert(prediction.sample_id.as_str(), prediction)
            .is_some()
        {
            return Err(BenchError::DuplicatePrediction {
                model_id: model_family_id.to_string(),
                sample_id: prediction.sample_id.clone(),
            });
        }
    }

    for observation in observations {
        let prediction = by_sample.get(observation.sample_id.as_str()).ok_or_else(|| {
            BenchError::MissingPrediction {
                model_id: model_family_id.to_string(),
                sample_id: observation.sample_id.clone(),
            }
        })?;
        // In v0 there is one scalar endpoint per run. Metric and unit are
        // therefore inherited from the observed trial schema and must not be
        // silently mixed across separate runs.
        let _ = prediction;
    }
    Ok(by_sample)
}

/// Score one model family on an exact sample-identity join.
pub fn score_model_family(
    model_family_id: &str,
    predictions: &[TrialPrediction],
    observations: &[TrialObservation],
) -> Result<PredictionScore, BenchError> {
    let by_sample =
        validate_prediction_join(model_family_id, predictions, observations)?;
    let mut squared_error = 0.0;
    let mut log_score = 0.0;
    let mut covered = 0usize;

    for observation in observations {
        let prediction = by_sample[observation.sample_id.as_str()];
        let error = observation.observed_value - prediction.mean;
        squared_error += error * error;
        log_score += gaussian_log_density(
            observation.observed_value,
            prediction.mean,
            prediction.standard_deviation,
        );
        let lower = prediction.mean - NORMAL_90 * prediction.standard_deviation;
        let upper = prediction.mean + NORMAL_90 * prediction.standard_deviation;
        if (lower..=upper).contains(&observation.observed_value) {
            covered += 1;
        }
    }

    let count = observations.len() as f64;
    Ok(PredictionScore {
        model_family_id: model_family_id.to_string(),
        trial_count: observations.len(),
        rmse: (squared_error / count).sqrt(),
        mean_log_predictive_density: log_score / count,
        coverage_90: covered as f64 / count,
    })
}

#[derive(Debug, Clone, PartialEq)]
pub struct PairedClusterComparison {
    pub candidate_model_id: String,
    pub baseline_model_id: String,
    /// Positive means the candidate assigned higher log predictive density.
    pub mean_log_score_delta: f64,
    pub confidence_level: f64,
    pub confidence_interval_lower: f64,
    pub confidence_interval_upper: f64,
    pub individual_cluster_count: usize,
    pub trial_count: usize,
    pub bootstrap_resamples: usize,
}

#[derive(Debug, Clone, Copy)]
struct SplitMix64(u64);

impl SplitMix64 {
    fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(SPLITMIX_GAMMA);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn index(&mut self, upper: usize) -> usize {
        (self.next_u64() as usize) % upper
    }

    fn unit_interval(&mut self) -> f64 {
        let mantissa = self.next_u64() >> 11;
        (mantissa as f64 + 0.5) / ((1u64 << 53) as f64)
    }

    fn standard_normal(&mut self) -> f64 {
        let u1 = self.unit_interval();
        let u2 = self.unit_interval();
        (-2.0 * u1.ln()).sqrt() * (std::f64::consts::TAU * u2).cos()
    }
}

/// Compare two model families on paired outcomes using an individual-cluster
/// bootstrap. Trials from one individual are resampled together to avoid
/// treating repeated steps from that individual as independent animals.
pub fn paired_cluster_bootstrap_log_score(
    candidate_model_id: &str,
    candidate_predictions: &[TrialPrediction],
    baseline_model_id: &str,
    baseline_predictions: &[TrialPrediction],
    observations: &[TrialObservation],
    bootstrap_resamples: usize,
    seed: u64,
) -> Result<PairedClusterComparison, BenchError> {
    if bootstrap_resamples < 100 {
        return Err(BenchError::InvalidBootstrapSamples);
    }
    let candidate = validate_prediction_join(
        candidate_model_id,
        candidate_predictions,
        observations,
    )?;
    let baseline =
        validate_prediction_join(baseline_model_id, baseline_predictions, observations)?;

    let mut clusters: BTreeMap<&str, Vec<f64>> = BTreeMap::new();
    let mut total_delta = 0.0;
    for observation in observations {
        let candidate_score = gaussian_log_density(
            observation.observed_value,
            candidate[observation.sample_id.as_str()].mean,
            candidate[observation.sample_id.as_str()].standard_deviation,
        );
        let baseline_score = gaussian_log_density(
            observation.observed_value,
            baseline[observation.sample_id.as_str()].mean,
            baseline[observation.sample_id.as_str()].standard_deviation,
        );
        let delta = candidate_score - baseline_score;
        total_delta += delta;
        clusters
            .entry(observation.individual_id.as_str())
            .or_default()
            .push(delta);
    }

    let cluster_values: Vec<&Vec<f64>> = clusters.values().collect();
    let cluster_count = cluster_values.len();
    let trial_count = observations.len();
    let mean_delta = total_delta / trial_count as f64;
    let mut rng = SplitMix64(seed);
    let mut replicates = Vec::with_capacity(bootstrap_resamples);

    for _ in 0..bootstrap_resamples {
        let mut sampled_sum = 0.0;
        let mut sampled_count = 0usize;
        for _ in 0..cluster_count {
            let cluster = cluster_values[rng.index(cluster_count)];
            sampled_sum += cluster.iter().sum::<f64>();
            sampled_count += cluster.len();
        }
        replicates.push(sampled_sum / sampled_count as f64);
    }

    replicates.sort_by(f64::total_cmp);
    let lower_index = ((bootstrap_resamples as f64 * 0.025).floor() as usize)
        .min(bootstrap_resamples - 1);
    let upper_index = ((bootstrap_resamples as f64 * 0.975).ceil() as usize)
        .min(bootstrap_resamples - 1);

    Ok(PairedClusterComparison {
        candidate_model_id: candidate_model_id.to_string(),
        baseline_model_id: baseline_model_id.to_string(),
        mean_log_score_delta: mean_delta,
        confidence_level: 0.95,
        confidence_interval_lower: replicates[lower_index],
        confidence_interval_upper: replicates[upper_index],
        individual_cluster_count: cluster_count,
        trial_count,
        bootstrap_resamples,
    })
}

/// Predictive distribution for one outcome metric under one model family.
#[derive(Debug, Clone, PartialEq)]
pub struct ModelOutcomeDistribution {
    pub model_family_id: String,
    pub metric_id: String,
    pub unit_id: String,
    pub mean: f64,
    pub standard_deviation: f64,
}

/// Candidate intervention with a model prediction for every competing family.
/// Cost must be measured in one declared, comparable budget unit within a run.
#[derive(Debug, Clone, PartialEq)]
pub struct InterventionCandidate {
    pub intervention_id: String,
    pub cost_units: f64,
    pub feasible: bool,
    pub predictions: Vec<ModelOutcomeDistribution>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct InterventionRanking {
    pub intervention_id: String,
    /// Monte Carlo estimate of I(Model; outcome | intervention), in nats.
    pub expected_information_gain_nats: f64,
    pub cost_units: f64,
    pub information_gain_per_cost: f64,
    pub model_family_count: usize,
    pub samples_per_model: usize,
}

fn log_sum_exp(values: &[f64]) -> f64 {
    let maximum = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    maximum + values.iter().map(|value| (value - maximum).exp()).sum::<f64>().ln()
}

fn gaussian_log_density_scalar(value: f64, distribution: &ModelOutcomeDistribution) -> f64 {
    gaussian_log_density(value, distribution.mean, distribution.standard_deviation)
}

/// Estimate mutual information between model identity and a scalar experimental
/// outcome under equal model priors. This is Monte Carlo Bayesian design, not a
/// pairwise-KL shortcut: each model generates outcomes and all model likelihoods
/// contribute to the posterior over model identity.
pub fn estimate_expected_information_gain(
    predictions: &[ModelOutcomeDistribution],
    samples_per_model: usize,
    seed: u64,
) -> Result<f64, BenchError> {
    if samples_per_model < 100 {
        return Err(BenchError::InvalidMonteCarloSamples);
    }
    if predictions.len() < 2 {
        return Err(BenchError::TooFewModelFamilies);
    }

    let first = &predictions[0];
    non_empty(&first.metric_id, "metric_id")?;
    non_empty(&first.unit_id, "unit_id")?;
    let mut model_ids = BTreeSet::new();
    for prediction in predictions {
        non_empty(&prediction.model_family_id, "model_family_id")?;
        if !model_ids.insert(prediction.model_family_id.as_str())
            || prediction.metric_id != first.metric_id
            || prediction.unit_id != first.unit_id
            || !prediction.mean.is_finite()
            || !prediction.standard_deviation.is_finite()
            || prediction.standard_deviation <= 0.0
        {
            return Err(BenchError::InvalidModelDistribution {
                intervention_id: "<direct-estimate>".to_string(),
                model_id: prediction.model_family_id.clone(),
            });
        }
    }

    let model_count = predictions.len();
    let log_prior = -(model_count as f64).ln();
    let mut rng = SplitMix64(seed);
    let mut information = 0.0;

    for (origin_index, origin) in predictions.iter().enumerate() {
        for _ in 0..samples_per_model {
            let outcome =
                origin.mean + origin.standard_deviation * rng.standard_normal();
            let log_likelihoods: Vec<f64> = predictions
                .iter()
                .map(|distribution| gaussian_log_density_scalar(outcome, distribution))
                .collect();
            let log_marginal = log_sum_exp(&log_likelihoods) + log_prior;
            information += log_likelihoods[origin_index] - log_marginal;
        }
    }

    let estimate = information / (model_count * samples_per_model) as f64;
    Ok(estimate.max(0.0).min((model_count as f64).ln()))
}

/// Rank feasible interventions by Monte Carlo expected information gain per
/// comparable cost unit. All candidates must predict the same model families,
/// metric and physical unit. Infeasible candidates remain unranked.
pub fn rank_interventions(
    candidates: &[InterventionCandidate],
    samples_per_model: usize,
    seed: u64,
) -> Result<Vec<InterventionRanking>, BenchError> {
    if samples_per_model < 100 {
        return Err(BenchError::InvalidMonteCarloSamples);
    }
    if candidates.is_empty() {
        return Ok(Vec::new());
    }

    let mut candidate_ids = BTreeSet::new();
    let mut expected_models: Option<BTreeSet<String>> = None;
    let mut expected_schema: Option<(String, String)> = None;
    let mut rankings = Vec::new();

    for candidate in candidates {
        non_empty(&candidate.intervention_id, "intervention_id")?;
        if !candidate_ids.insert(candidate.intervention_id.as_str()) {
            return Err(BenchError::DuplicateInterventionId(
                candidate.intervention_id.clone(),
            ));
        }
        if !candidate.cost_units.is_finite() || candidate.cost_units <= 0.0 {
            return Err(BenchError::InvalidInterventionCost {
                intervention_id: candidate.intervention_id.clone(),
            });
        }
        if candidate.predictions.len() < 2 {
            return Err(BenchError::TooFewModelFamilies);
        }

        let mut ids = BTreeSet::new();
        for prediction in &candidate.predictions {
            non_empty(&prediction.model_family_id, "model_family_id")?;
            non_empty(&prediction.metric_id, "metric_id")?;
            non_empty(&prediction.unit_id, "unit_id")?;
            if !ids.insert(prediction.model_family_id.clone())
                || !prediction.mean.is_finite()
                || !prediction.standard_deviation.is_finite()
                || prediction.standard_deviation <= 0.0
            {
                return Err(BenchError::InvalidModelDistribution {
                    intervention_id: candidate.intervention_id.clone(),
                    model_id: prediction.model_family_id.clone(),
                });
            }
        }
        let schema = (
            candidate.predictions[0].metric_id.clone(),
            candidate.predictions[0].unit_id.clone(),
        );
        if candidate
            .predictions
            .iter()
            .any(|prediction| (prediction.metric_id.clone(), prediction.unit_id.clone()) != schema)
        {
            return Err(BenchError::InconsistentOutcomeSchema {
                intervention_id: candidate.intervention_id.clone(),
            });
        }

        if let Some(expected) = &expected_models {
            if expected != &ids {
                return Err(BenchError::ModelFamilySetMismatch {
                    intervention_id: candidate.intervention_id.clone(),
                });
            }
        } else {
            expected_models = Some(ids);
        }
        if let Some(expected) = &expected_schema {
            if expected != &schema {
                return Err(BenchError::InconsistentOutcomeSchema {
                    intervention_id: candidate.intervention_id.clone(),
                });
            }
        } else {
            expected_schema = Some(schema);
        }

        if !candidate.feasible {
            continue;
        }

        let candidate_seed = seed ^ stable_hash(&candidate.intervention_id);
        let eig = estimate_expected_information_gain(
            &candidate.predictions,
            samples_per_model,
            candidate_seed,
        )?;
        rankings.push(InterventionRanking {
            intervention_id: candidate.intervention_id.clone(),
            expected_information_gain_nats: eig,
            cost_units: candidate.cost_units,
            information_gain_per_cost: eig / candidate.cost_units,
            model_family_count: candidate.predictions.len(),
            samples_per_model,
        });
    }

    rankings.sort_by(|a, b| {
        b.information_gain_per_cost
            .total_cmp(&a.information_gain_per_cost)
            .then_with(|| a.intervention_id.cmp(&b.intervention_id))
    });
    Ok(rankings)
}

fn stable_hash(value: &str) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for byte in value.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

