impl std::error::Error for BenchError {}

fn non_empty(value: &str, field: &'static str) -> Result<(), BenchError> {
    if value.trim().is_empty() {
        Err(BenchError::EmptyIdentifier { field })
    } else {
        Ok(())
    }
}

fn validate_observations(observations: &[TrialObservation]) -> Result<(), BenchError> {
    if observations.is_empty() {
        return Err(BenchError::EmptyDataset);
    }
    let mut sample_ids = BTreeSet::new();
    for row in observations {
        non_empty(&row.sample_id, "sample_id")?;
        non_empty(&row.individual_id, "individual_id")?;
        non_empty(&row.connectome_dataset_id, "connectome_dataset_id")?;
        non_empty(&row.intervention_family_id, "intervention_family_id")?;
        non_empty(&row.condition_id, "condition_id")?;
        non_empty(&row.metric_id, "metric_id")?;
        non_empty(&row.unit_id, "unit_id")?;
        if !row.observed_value.is_finite() {
            return Err(BenchError::InvalidObservedValue {
                sample_id: row.sample_id.clone(),
            });
        }
        if !sample_ids.insert(row.sample_id.as_str()) {
            return Err(BenchError::DuplicateSampleId(row.sample_id.clone()));
        }
    }
    let schema = (&observations[0].metric_id, &observations[0].unit_id);
    if observations
        .iter()
        .any(|row| (&row.metric_id, &row.unit_id) != schema)
    {
        return Err(BenchError::EmptyOutcomeMetric);
    }
    Ok(())
}

/// Assign all members of explicitly held-out groups to the test partition.
/// Rows matching more than one held-out dimension retain every reason.
pub fn build_group_held_out_split(
    observations: &[TrialObservation],
    policy: &SplitPolicy,
) -> Result<TrialSplit, BenchError> {
    validate_observations(observations)?;
    if policy.held_out_intervention_families.is_empty()
        && policy.held_out_conditions.is_empty()
        && policy.held_out_individuals.is_empty()
        && policy.held_out_connectome_datasets.is_empty()
    {
        return Err(BenchError::EmptyHoldoutPolicy);
    }

    for id in &policy.held_out_intervention_families {
        non_empty(id, "held_out_intervention_family")?;
    }
    for id in &policy.held_out_conditions {
        non_empty(id, "held_out_condition")?;
    }
    for id in &policy.held_out_individuals {
        non_empty(id, "held_out_individual")?;
    }
    for id in &policy.held_out_connectome_datasets {
        non_empty(id, "held_out_connectome_dataset")?;
    }

    let observed_interventions: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.intervention_family_id.as_str())
        .collect();
    let observed_conditions: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.condition_id.as_str())
        .collect();
    let observed_individuals: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.individual_id.as_str())
        .collect();
    let observed_datasets: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.connectome_dataset_id.as_str())
        .collect();

    for id in &policy.held_out_intervention_families {
        if !observed_interventions.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "intervention_family",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_conditions {
        if !observed_conditions.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "condition",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_individuals {
        if !observed_individuals.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "individual",
                value: id.clone(),
            });
        }
    }
    for id in &policy.held_out_connectome_datasets {
        if !observed_datasets.contains(id.as_str()) {
            return Err(BenchError::UnobservedHoldoutGroup {
                field: "connectome_dataset",
                value: id.clone(),
            });
        }
    }

    let mut split = TrialSplit {
        training_indices: Vec::new(),
        held_out_indices: Vec::new(),
        held_out_reasons: BTreeMap::new(),
    };
    for (index, row) in observations.iter().enumerate() {
        let mut reasons = Vec::new();
        if policy
            .held_out_intervention_families
            .contains(&row.intervention_family_id)
        {
            reasons.push(HoldoutReason::InterventionFamily);
        }
        if policy.held_out_conditions.contains(&row.condition_id) {
            reasons.push(HoldoutReason::Condition);
        }
        if policy.held_out_individuals.contains(&row.individual_id) {
            reasons.push(HoldoutReason::Individual);
        }
        if policy
            .held_out_connectome_datasets
            .contains(&row.connectome_dataset_id)
        {
            reasons.push(HoldoutReason::ConnectomeDataset);
        }

        if reasons.is_empty() {
            split.training_indices.push(index);
        } else {
            split.held_out_indices.push(index);
            split
                .held_out_reasons
                .insert(row.sample_id.clone(), reasons);
        }
    }

    if split.training_indices.is_empty() {
        return Err(BenchError::EmptyTrainingPartition);
    }
    if split.held_out_indices.is_empty() {
        return Err(BenchError::EmptyHeldOutPartition);
    }

    // Defensive postcondition: no training row may match any held-out group.
    for index in &split.training_indices {
        let row = &observations[*index];
        if policy
            .held_out_intervention_families
            .contains(&row.intervention_family_id)
            || policy.held_out_conditions.contains(&row.condition_id)
            || policy.held_out_individuals.contains(&row.individual_id)
            || policy
                .held_out_connectome_datasets
                .contains(&row.connectome_dataset_id)
        {
            return Err(BenchError::EmptyTrainingPartition);
        }
    }
    Ok(split)
}

/// Enforce the maximum scientific claim permitted by the supplied provenance.
/// Synthetic and in-silico rows can never be promoted to empirical replication.
pub fn validate_evidence_claim(
    observations: &[TrialObservation],
    claim: EvidenceClaim,
) -> Result<(), BenchError> {
    validate_observations(observations)?;
    let classes: BTreeSet<EvidenceClass> =
        observations.iter().map(|row| row.evidence_class).collect();

    let accepted = match claim {
        EvidenceClaim::SyntheticHarness => {
            classes == BTreeSet::from([EvidenceClass::SyntheticFixture])
        }
        EvidenceClaim::InSilicoDemonstration => {
            classes.iter().all(|class| {
                matches!(
                    class,
                    EvidenceClass::InSilicoGenerated | EvidenceClass::SyntheticFixture
                )
            }) && classes.contains(&EvidenceClass::InSilicoGenerated)
        }
        EvidenceClaim::PreprintReproduction => {
            classes.iter().all(|class| {
                matches!(
                    class,
                    EvidenceClass::PreprintMeasured | EvidenceClass::PeerReviewedMeasured
                )
            }) && classes.contains(&EvidenceClass::PreprintMeasured)
        }
        EvidenceClaim::PeerReviewedReplication => {
            classes == BTreeSet::from([EvidenceClass::PeerReviewedMeasured])
        }
        EvidenceClaim::CrossDatasetGeneralization => {
            classes == BTreeSet::from([EvidenceClass::PeerReviewedMeasured])
                && observations
                    .iter()
                    .map(|row| row.connectome_dataset_id.as_str())
                    .collect::<BTreeSet<_>>()
                    .len()
                    >= 2
                && observations
                    .iter()
                    .map(|row| row.individual_id.as_str())
                    .collect::<BTreeSet<_>>()
                    .len()
                    >= 2
        }
    };

    if accepted {
        Ok(())
    } else {
        Err(BenchError::EvidenceClaimNotSupported { claim })
    }
}

/// One scalar Gaussian prediction for one sample from one model family.
#[derive(Debug, Clone, PartialEq)]
pub struct TrialPrediction {
    pub model_family_id: String,
    pub sample_id: String,
    pub metric_id: String,
    pub unit_id: String,
    pub mean: f64,
    pub standard_deviation: f64,
}

#[derive(Debug, Clone, PartialEq)]
pub struct PredictionScore {
    pub model_family_id: String,
    pub trial_count: usize,
    pub rmse: f64,
    /// Mean per-trial Gaussian log predictive density; larger is better.
    pub mean_log_predictive_density: f64,
    /// Empirical coverage of the Gaussian central 90% predictive interval.
    pub coverage_90: f64,
}

fn gaussian_log_density(value: f64, mean: f64, standard_deviation: f64) -> Option<f64> {
    if !value.is_finite()
        || !mean.is_finite()
        || !standard_deviation.is_finite()
        || standard_deviation <= 0.0
    {
        return None;
    }
    let z = (value - mean) / standard_deviation;
    let log_density = -LOG_SQRT_2PI - standard_deviation.ln() - 0.5 * z * z;
    log_density.is_finite().then_some(log_density)
}

fn validate_prediction_join<'a>(
    model_family_id: &str,
    predictions: &'a [TrialPrediction],
    observations: &[TrialObservation],
) -> Result<BTreeMap<&'a str, &'a TrialPrediction>, BenchError> {
    validate_observations(observations)?;
    non_empty(model_family_id, "model_family_id")?;
    let known_samples: BTreeSet<&str> = observations
        .iter()
        .map(|row| row.sample_id.as_str())
        .collect();
    let mut by_sample = BTreeMap::new();

    for prediction in predictions {
        if prediction.model_family_id != model_family_id {
            return Err(BenchError::PredictionModelMismatch {
                expected: model_family_id.to_string(),
                actual: prediction.model_family_id.clone(),
            });
        }
        non_empty(&prediction.sample_id, "prediction.sample_id")?;
        non_empty(&prediction.metric_id, "prediction.metric_id")?;
        non_empty(&prediction.unit_id, "prediction.unit_id")?;
        if !known_samples.contains(prediction.sample_id.as_str()) {
            return Err(BenchError::UnexpectedPrediction {
                model_id: model_family_id.to_string(),
                sample_id: prediction.sample_id.clone(),
            });
        }
        if !prediction.mean.is_finite()
            || !prediction.standard_deviation.is_finite()
            || prediction.standard_deviation <= 0.0
        {
            return Err(BenchError::InvalidPrediction {
                sample_id: prediction.sample_id.clone(),
            });
        }
        if by_sample
            .insert(prediction.sample_id.as_str(), prediction)
            .is_some()
        {
            return Err(BenchError::DuplicatePrediction {
                model_id: model_family_id.to_string(),
                sample_id: prediction.sample_id.clone(),
            });
        }
    }

    for observation in observations {
        let prediction = by_sample
            .get(observation.sample_id.as_str())
            .ok_or_else(|| BenchError::MissingPrediction {
                model_id: model_family_id.to_string(),
                sample_id: observation.sample_id.clone(),
            })?;
        if prediction.metric_id != observation.metric_id
            || prediction.unit_id != observation.unit_id
        {
            return Err(BenchError::PredictionSchemaMismatch {
                sample_id: observation.sample_id.clone(),
            });
        }
    }
    Ok(by_sample)
}

/// Score one model family on an exact sample-identity join.
pub fn score_model_family(
    model_family_id: &str,
    predictions: &[TrialPrediction],
    observations: &[TrialObservation],
) -> Result<PredictionScore, BenchError> {
    let by_sample = validate_prediction_join(model_family_id, predictions, observations)?;
    let mut squared_error = 0.0;
    let mut log_score = 0.0;
    let mut covered = 0usize;

    for observation in observations {
        let prediction = by_sample[observation.sample_id.as_str()];
        let error = observation.observed_value - prediction.mean;
        squared_error += error * error;
        log_score += gaussian_log_density(
            observation.observed_value,
            prediction.mean,
            prediction.standard_deviation,
        )
        .ok_or_else(|| BenchError::InvalidPrediction {
            sample_id: observation.sample_id.clone(),
        })?;
        let lower = prediction.mean - NORMAL_90 * prediction.standard_deviation;
        let upper = prediction.mean + NORMAL_90 * prediction.standard_deviation;
        if (lower..=upper).contains(&observation.observed_value) {
            covered += 1;
        }
    }

    let count = observations.len() as f64;
    Ok(PredictionScore {
        model_family_id: model_family_id.to_string(),
        trial_count: observations.len(),
        rmse: (squared_error / count).sqrt(),
        mean_log_predictive_density: log_score / count,
        coverage_90: covered as f64 / count,
    })
}

