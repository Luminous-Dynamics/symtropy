/// Primary status of one argument assessment.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AssuranceStatus {
    /// Structurally complete for independent review only; never permission to operate.
    ReviewReadyOnly,
    /// Required argument, hazard, evidence or decision record is missing.
    IncompleteArgument,
    /// One or more mandatory defeaters remain open or unknown.
    BlockedByOpenDefeater,
    /// Evidence is unsupported, contradicted, stale, planning-only or invalid for the case.
    BlockedByUnsupportedOrStaleEvidence,
    /// One or more nodes/evidence references have a different case or operational scope.
    BlockedByScopeMismatch,
    /// Evidence, independence or owner assessment is indeterminate.
    Indeterminate,
}

