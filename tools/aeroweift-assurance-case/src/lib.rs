//! Structural evaluator for evidence-linked aviation operational assurance cases.
//!
//! The positive result is deliberately REVIEW_READY_ONLY. This crate does not
//! calculate risk, authenticate signatures, establish physical truth, accept residual
//! risk, authorize an operation, grant clearance or certify an aircraft.

#![forbid(unsafe_code)]
#![warn(missing_docs)]

use std::collections::{BTreeMap, BTreeSet, VecDeque};

/// Exact operational/case scope shared by all argument and evidence nodes.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AssuranceCaseScope {
    /// Stable case identifier.
    pub case_id: String,
    /// Frozen campaign manifest digest.
    pub campaign_sha256: String,
    /// Operation/mission identifier.
    pub operation_id: String,
    /// Pseudonymous aircraft identity.
    pub aircraft_id: String,
    /// Exact flight identity.
    pub flight_id: String,
    /// Authorization identifier being assessed; this is not an authorization grant.
    pub authorization_id: String,
    /// Authorization revision.
    pub authorization_revision: u64,
    /// Exact operational-intent digest.
    pub intent_sha256: String,
    /// Intended-use/risk profile digest.
    pub profile_sha256: String,
    /// Operating-domain envelope digest.
    pub operating_domain_sha256: String,
    /// Time-scale identity; no implicit clock conversion is performed.
    pub time_scale_id: String,
    /// Horizontal coordinate-frame identity.
    pub horizontal_frame_id: String,
    /// Vertical datum identity.
    pub vertical_datum_id: String,
    /// Inclusive beginning of the proposed operation window.
    pub operation_start: i64,
    /// Exclusive end of the proposed operation window.
    pub operation_end: i64,
    /// Effective-time cutoff for all current-applicability claims.
    pub effective_cutoff: i64,
    /// Knowledge-time cutoff for reproducible historical reconstruction.
    pub knowledge_cutoff: i64,
}

impl AssuranceCaseScope {
    fn is_complete(&self) -> bool {
        !self.case_id.trim().is_empty()
            && is_sha256(&self.campaign_sha256)
            && !self.operation_id.trim().is_empty()
            && !self.aircraft_id.trim().is_empty()
            && !self.flight_id.trim().is_empty()
            && !self.authorization_id.trim().is_empty()
            && is_sha256(&self.intent_sha256)
            && is_sha256(&self.profile_sha256)
            && is_sha256(&self.operating_domain_sha256)
            && !self.time_scale_id.trim().is_empty()
            && !self.horizontal_frame_id.trim().is_empty()
            && !self.vertical_datum_id.trim().is_empty()
            && self.operation_start >= 0
            && self.operation_start < self.operation_end
            && self.operation_start <= self.effective_cutoff
            && self.effective_cutoff < self.operation_end
            && self.knowledge_cutoff >= 0
    }
}

/// Kind of node in the typed assurance argument graph.
#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum NodeKind {
    /// Top-level argument claim.
    TopClaim,
    /// Decomposed assurance subclaim.
    Claim,
    /// Argument strategy that decomposes a claim into subclaims.
    Strategy,
    /// Operational context statement.
    Context,
    /// Explicit assumption with owner and validity.
    Assumption,
    /// Identified operational hazard.
    Hazard,
    /// Named mitigation or control for a hazard.
    Mitigation,
    /// Evidence receipt or independently sourced observation.
    Evidence,
    /// Defeater, challenge or counterargument.
    Defeater,
    /// External authority decision record; never generated by this evaluator.
    AuthorityDecision,
}

/// State of a claim as stated by its owner/evidence evaluator.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ClaimState {
    /// Owner asserts the claim is supported under its exact declared scope.
    Supported,
    /// Qualified evidence contradicts the claim.
    Contradicted,
    /// Evidence is missing, incomplete or not assessable.
    Indeterminate,
    /// The claim is unsupported by its declared evidence profile.
    Unsupported,
}

