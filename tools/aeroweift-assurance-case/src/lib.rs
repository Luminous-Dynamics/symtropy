/// One blocker tied to a stable node/requirement identity.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CaseBlocker {
    /// Node ID, hazard ID or required authority role.
    pub subject_id: String,
    /// Reason.
    pub reason: BlockerReason,
}

/// Structural input error. These are distinct from incomplete/blocked assurance cases.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EvaluationError {
    /// Frozen policy is incomplete or internally inconsistent.
    InvalidPolicy,
    /// Declared case scope is incomplete or has an invalid operation window.
    InvalidScope,
    /// Duplicate node identity.
    DuplicateNodeId,
    /// Duplicate typed edge.
    DuplicateEdge,
    /// Edge references a missing node.
    MissingNode,
    /// Edge kind is incompatible with endpoint node types.
    EdgeTypeMismatch,
    /// Graph contains a directed cycle.
    GraphCycle,
    /// One or more nodes are disconnected from the declared root.
    OrphanNode,
    /// Node metadata/digest/validity or kind-specific payload is malformed.
    InvalidNode,
    /// Node scope differs from the exact expected case scope.
    ScopeMismatch,
    /// Evidence cutoff differs from the exact case effective/knowledge cutoffs.
    EvidenceCutoffMismatch,
    /// Duplicate hazard identity.
    DuplicateHazard,
    /// Duplicate authority decision for the same role/identity.
    DuplicateAuthorityDecision,
    /// The declared evidence proposition is incompatible with its source owner kind.
    EvidencePurposeSourceMismatch,
    /// A hazard is present but absent from the frozen hazard manifest.
    HazardNotInRequiredManifest,
    /// A node's validity does not cover the entire proposed operation window.
    NodeValidityDoesNotCoverOperation,
}

/// Complete result of evaluating one assurance case.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AssuranceResult {
    /// Primary structural status.
    pub status: AssuranceStatus,
    /// Exact case identity.
    pub case_id: String,
    /// Declared top-level claim node.
    pub root_claim_id: String,
    /// Frozen policy digest.
    pub policy_sha256: String,
    /// Verifier build digest.
    pub verifier_build_sha256: String,
    /// All blockers in stable deterministic order.
    pub blockers: Vec<CaseBlocker>,
    /// Required authority roles with no accepted, current decision.
    pub outstanding_authority_roles: Vec<String>,
    /// Number of unique declared correlation groups supporting each claim.
    pub independent_evidence_groups_by_claim: Vec<(String, usize)>,
    /// Explicit statement of the claim ceiling.
    pub permission_granted: bool,
}

fn is_sha256(value: &str) -> bool {
    value.len() == 64 && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

fn validate_scope(scope: &AssuranceCaseScope) -> Result<(), EvaluationError> {
    if !scope.is_complete() {
        return Err(EvaluationError::InvalidScope);
    }
    Ok(())
}

fn validate_policy(policy: &AssuranceCasePolicy) -> Result<(), EvaluationError> {
    validate_scope(&policy.expected_scope)?;
    if !is_sha256(&policy.policy_sha256)
        || !is_sha256(&policy.verifier_build_sha256)
        || policy.required_claim_evidence.is_empty()
        || policy.required_mitigation_evidence.is_empty()
        || policy.required_hazards.is_empty()
        || policy
            .required_hazards
            .iter()
            .any(|value| value.trim().is_empty())
        || policy.required_authorities.is_empty()
        || policy
            .required_authorities
            .iter()
            .any(|item| item.role.trim().is_empty() || item.authority_id.trim().is_empty())
    {
        return Err(EvaluationError::InvalidPolicy);
    }
    let claim_requirement_ids: BTreeSet<&str> = policy
        .required_claim_evidence
        .iter()
        .map(|item| item.claim_id.as_str())
        .collect();
    if claim_requirement_ids.len() != policy.required_claim_evidence.len()
        || policy.required_claim_evidence.iter().any(|item| {
            item.claim_id.trim().is_empty()
                || item
                    .required_purposes
                    .iter()
                    .copied()
                    .collect::<BTreeSet<_>>()
                    .len()
                    != item.required_purposes.len()
        })
    {
        return Err(EvaluationError::InvalidPolicy);
    }
    let mitigation_requirement_ids: BTreeSet<&str> = policy
        .required_mitigation_evidence
        .iter()
        .map(|item| item.mitigation_id.as_str())
        .collect();
    if mitigation_requirement_ids.len() != policy.required_mitigation_evidence.len()
        || policy.required_mitigation_evidence.iter().any(|item| {
            item.mitigation_id.trim().is_empty()
                || item.required_purposes.is_empty()
                || item
                    .required_purposes
                    .iter()
                    .copied()
                    .collect::<BTreeSet<_>>()
                    .len()
                    != item.required_purposes.len()
        })
    {
        return Err(EvaluationError::InvalidPolicy);
    }
    let hazards: BTreeSet<&str> = policy.required_hazards.iter().map(String::as_str).collect();
    if hazards.len() != policy.required_hazards.len() {
        return Err(EvaluationError::InvalidPolicy);
    }
    let authorities: BTreeSet<(&str, &str)> = policy
        .required_authorities
        .iter()
        .map(|item| (item.role.as_str(), item.authority_id.as_str()))
        .collect();
    if authorities.len() != policy.required_authorities.len() {
        return Err(EvaluationError::InvalidPolicy);
    }
    Ok(())
}

fn evidence_purpose_matches_source(source: EvidenceSourceKind, purpose: EvidencePurpose) -> bool {
    matches!(
        (source, purpose),
        (EvidenceSourceKind::TrackL, EvidencePurpose::PntReachability)
            | (
                EvidenceSourceKind::TrackM,
                EvidencePurpose::SurveillanceObservability
            )
            | (
                EvidenceSourceKind::TrackN,
                EvidencePurpose::IntentConformance
            )
            | (
                EvidenceSourceKind::TrackP,
                EvidencePurpose::CausalReceiptBinding
            )
            | (
                EvidenceSourceKind::TrackQ,
                EvidencePurpose::AuthenticatedCustody
            )
            | (
                EvidenceSourceKind::TrackR,
                EvidencePurpose::ConflictPerformance
            )
            | (
                EvidenceSourceKind::TrackS,
                EvidencePurpose::MultiSubjectScope
            )
            | (
                EvidenceSourceKind::TrackT,
                EvidencePurpose::ModelCredibility
            )
            | (
                EvidenceSourceKind::TrackU,
                EvidencePurpose::ModelRequalification
            )
            | (
                EvidenceSourceKind::TrackVPlanning,
                EvidencePurpose::ExperimentPlan
            )
            | (
                EvidenceSourceKind::ExternalFlightTest,
                EvidencePurpose::PhysicalMitigationEffectiveness
            )
            | (
                EvidenceSourceKind::ExternalMeasurement,
                EvidencePurpose::PhysicalMitigationEffectiveness
                    | EvidencePurpose::ReferenceMeasurement
            )
            | (
                EvidenceSourceKind::ExternalAuthority,
                EvidencePurpose::ExternalAuthorityRecord
            )
            | (
                EvidenceSourceKind::GenericSoftwareCi,
                EvidencePurpose::GenericSoftwareVerification
            )
            | (EvidenceSourceKind::Other, EvidencePurpose::Unclassified)
    )
}

fn validate_node_shape(node: &AssuranceNode) -> Result<(), EvaluationError> {
    if node.node_id.trim().is_empty()
        || !is_sha256(&node.payload_sha256)
        || node.owner_role.trim().is_empty()
        || node.revision.trim().is_empty()
        || node.valid_from < 0
        || node.valid_until <= node.valid_from
    {
        return Err(EvaluationError::InvalidNode);
    }
    let kind_valid = match node.kind {
        NodeKind::TopClaim | NodeKind::Claim => {
            node.claim.is_some()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
        NodeKind::Assumption => {
            node.claim.is_none()
                && node
                    .assumption
                    .as_ref()
                    .is_some_and(|x| !x.assumption_id.trim().is_empty())
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
        NodeKind::Hazard => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node
                    .hazard_id
                    .as_ref()
                    .is_some_and(|x| !x.trim().is_empty())
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
        NodeKind::Mitigation => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_some()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
        NodeKind::Evidence => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_some()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
        NodeKind::Defeater => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node
                    .defeater
                    .as_ref()
                    .is_some_and(|x| !x.defeater_id.trim().is_empty())
                && node.authority_decision.is_none()
        }
        NodeKind::AuthorityDecision => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.as_ref().is_some_and(|x| {
                    !x.role.trim().is_empty()
                        && !x.authority_id.trim().is_empty()
                        && x.effective_at >= 0
                        && x.recorded_at >= 0
                        && x.valid_until.is_none_or(|end| end > x.effective_at)
                        && is_sha256(&x.conditions_sha256)
                })
        }
        NodeKind::Strategy | NodeKind::Context => {
            node.claim.is_none()
                && node.assumption.is_none()
                && node.hazard_id.is_none()
                && node.mitigation_state.is_none()
                && node.evidence.is_none()
                && node.defeater.is_none()
                && node.authority_decision.is_none()
        }
    };
    if !kind_valid {
        return Err(EvaluationError::InvalidNode);
    }
    if let Some(evidence) = &node.evidence {
        if evidence.source_receipt_id.trim().is_empty()
            || !is_sha256(&evidence.source_payload_sha256)
            || !is_sha256(&evidence.source_assessment_sha256)
            || evidence
                .correlation_group_id
                .as_ref()
                .is_some_and(|value| value.trim().is_empty())
        {
            return Err(EvaluationError::InvalidNode);
        }
        if !evidence_purpose_matches_source(evidence.source_kind, evidence.purpose) {
            return Err(EvaluationError::EvidencePurposeSourceMismatch);
        }
    }
    Ok(())
}

fn edge_type_valid(edge: &AssuranceEdge, nodes: &BTreeMap<&str, &AssuranceNode>) -> bool {
    let Some(from) = nodes.get(edge.from_node_id.as_str()) else {
        return false;
    };
    let Some(to) = nodes.get(edge.to_node_id.as_str()) else {
        return false;
    };
    match edge.kind {
        EdgeKind::Decomposes => matches!(
            (from.kind, to.kind),
            (NodeKind::TopClaim | NodeKind::Claim, NodeKind::Strategy)
                | (
                    NodeKind::TopClaim | NodeKind::Claim | NodeKind::Strategy,
                    NodeKind::Claim
                )
        ),
        EdgeKind::Supports => {
            from.kind == NodeKind::Evidence
                && matches!(
                    to.kind,
                    NodeKind::TopClaim
                        | NodeKind::Claim
                        | NodeKind::Mitigation
                        | NodeKind::Assumption
                )
        }
        EdgeKind::Contextualizes => {
            from.kind == NodeKind::Context
                && matches!(
                    to.kind,
                    NodeKind::TopClaim | NodeKind::Claim | NodeKind::Strategy | NodeKind::Hazard
                )
        }
        EdgeKind::Assumes => {
            from.kind == NodeKind::Assumption
                && matches!(
                    to.kind,
                    NodeKind::TopClaim | NodeKind::Claim | NodeKind::Strategy
                )
        }
        EdgeKind::AddressesHazard => {
            matches!(
                from.kind,
                NodeKind::TopClaim | NodeKind::Claim | NodeKind::Strategy
            ) && to.kind == NodeKind::Hazard
        }
        EdgeKind::Mitigates => from.kind == NodeKind::Mitigation && to.kind == NodeKind::Hazard,
        EdgeKind::Discharges => from.kind == NodeKind::Evidence && to.kind == NodeKind::Defeater,
        EdgeKind::Challenges => {
            from.kind == NodeKind::Defeater
                && matches!(
                    to.kind,
                    NodeKind::TopClaim | NodeKind::Claim | NodeKind::Mitigation
                )
        }
        EdgeKind::RequiresDecision => {
            to.kind == NodeKind::AuthorityDecision
                && matches!(
                    from.kind,
                    NodeKind::TopClaim
                        | NodeKind::Claim
                        | NodeKind::Hazard
                        | NodeKind::Assumption
                        | NodeKind::Defeater
                )
        }
    }
}

fn graph_is_acyclic(nodes: &[AssuranceNode], edges: &[AssuranceEdge]) -> bool {
    let mut indegree: BTreeMap<&str, usize> = nodes
        .iter()
        .map(|node| (node.node_id.as_str(), 0))
        .collect();
    let mut adjacency: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for edge in edges {
        *indegree.entry(edge.to_node_id.as_str()).or_default() += 1;
        adjacency
            .entry(edge.from_node_id.as_str())
            .or_default()
            .push(edge.to_node_id.as_str());
    }
    let mut queue: VecDeque<&str> = indegree
        .iter()
        .filter_map(|(id, degree)| (*degree == 0).then_some(*id))
        .collect();
    let mut visited = 0;
    while let Some(id) = queue.pop_front() {
        visited += 1;
        if let Some(children) = adjacency.get(id) {
            for child in children {
                let degree = indegree
                    .get_mut(child)
                    .expect("edge target was pre-validated");
                *degree -= 1;
                if *degree == 0 {
                    queue.push_back(child);
                }
            }
        }
    }
    visited == nodes.len()
}

fn graph_is_root_connected(
    nodes: &[AssuranceNode],
    edges: &[AssuranceEdge],
    root_id: &str,
) -> bool {
    let mut adjacency: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for edge in edges {
        adjacency
            .entry(edge.from_node_id.as_str())
            .or_default()
            .push(edge.to_node_id.as_str());
        adjacency
            .entry(edge.to_node_id.as_str())
            .or_default()
            .push(edge.from_node_id.as_str());
    }
    let mut reached = BTreeSet::new();
    let mut queue = VecDeque::from([root_id]);
    while let Some(id) = queue.pop_front() {
        if !reached.insert(id) {
            continue;
        }
        if let Some(neighbours) = adjacency.get(id) {
            queue.extend(neighbours.iter().copied());
        }
    }
    reached.len() == nodes.len()
}

fn add_blocker(blockers: &mut BTreeSet<(String, BlockerReason)>, id: &str, reason: BlockerReason) {
    blockers.insert((id.to_owned(), reason));
}

/// Evaluate one assurance-case argument under an exact scope and policy.
///
/// This function does not calculate risk or establish that the proposed operation is safe.
/// Its strongest positive output is REVIEW_READY_ONLY.
pub fn evaluate_assurance_case(
    nodes: &[AssuranceNode],
    edges: &[AssuranceEdge],
    root_claim_id: &str,
    policy: &AssuranceCasePolicy,
) -> Result<AssuranceResult, EvaluationError> {
    validate_policy(policy)?;
    let mut by_id: BTreeMap<&str, &AssuranceNode> = BTreeMap::new();
    let mut hazards = BTreeSet::new();
    for node in nodes {
        validate_node_shape(node)?;
        if node.scope != policy.expected_scope {
            return Err(EvaluationError::ScopeMismatch);
        }
        if node.valid_from > policy.expected_scope.operation_start
            || node.valid_until < policy.expected_scope.operation_end
        {
            // Every relied-on case node must remain valid throughout the proposed operation.
            return Err(EvaluationError::NodeValidityDoesNotCoverOperation);
        }
        if let Some(hazard_id) = &node.hazard_id {
            if !hazards.insert(hazard_id.as_str()) {
                return Err(EvaluationError::DuplicateHazard);
            }
            if !policy
                .required_hazards
                .iter()
                .any(|required| required == hazard_id)
            {
                return Err(EvaluationError::HazardNotInRequiredManifest);
            }
        }
        if by_id.insert(node.node_id.as_str(), node).is_some() {
            return Err(EvaluationError::DuplicateNodeId);
        }
    }
    let Some(root) = by_id.get(root_claim_id).copied() else {
        return Err(EvaluationError::MissingNode);
    };
    if root.kind != NodeKind::TopClaim {
        return Err(EvaluationError::InvalidNode);
    }

    let mut unique_edges = BTreeSet::new();
    for edge in edges {
        if edge.from_node_id.trim().is_empty()
            || edge.to_node_id.trim().is_empty()
            || !by_id.contains_key(edge.from_node_id.as_str())
            || !by_id.contains_key(edge.to_node_id.as_str())
        {
            return Err(EvaluationError::MissingNode);
        }
        if !unique_edges.insert((
            edge.from_node_id.as_str(),
            edge.to_node_id.as_str(),
            edge.kind,
        )) {
            return Err(EvaluationError::DuplicateEdge);
        }
        if !edge_type_valid(edge, &by_id) {
            return Err(EvaluationError::EdgeTypeMismatch);
        }
    }
    if !graph_is_acyclic(nodes, edges) {
        return Err(EvaluationError::GraphCycle);
    }
    if !graph_is_root_connected(nodes, edges, root_claim_id) {
        return Err(EvaluationError::OrphanNode);
    }

    let mut blockers = BTreeSet::new();
    let mut groups_by_claim = Vec::new();

    for requirement in &policy.required_claim_evidence {
        if !by_id
            .get(requirement.claim_id.as_str())
            .is_some_and(|node| matches!(node.kind, NodeKind::TopClaim | NodeKind::Claim))
        {
            add_blocker(
                &mut blockers,
                &requirement.claim_id,
                BlockerReason::EvidenceRequirementTargetMissing,
            );
        }
    }
    for requirement in &policy.required_mitigation_evidence {
        if !by_id
            .get(requirement.mitigation_id.as_str())
            .is_some_and(|node| node.kind == NodeKind::Mitigation)
        {
            add_blocker(
                &mut blockers,
                &requirement.mitigation_id,
                BlockerReason::EvidenceRequirementTargetMissing,
            );
        }
    }

    // The top-level argument must be decomposed into at least one named strategy.
    if !edges.iter().any(|edge| {
        edge.from_node_id == root_claim_id
            && edge.kind == EdgeKind::Decomposes
            && by_id
                .get(edge.to_node_id.as_str())
                .is_some_and(|node| node.kind == NodeKind::Strategy)
    }) {
        add_blocker(
            &mut blockers,
            root_claim_id,
            BlockerReason::MissingDecompositionStrategy,
        );
    }

    // Strategies must resolve into claims; claims must have a support path.
    for node in nodes {
        if node.kind == NodeKind::Strategy
            && !edges.iter().any(|edge| {
                edge.from_node_id == node.node_id
                    && edge.kind == EdgeKind::Decomposes
                    && by_id
                        .get(edge.to_node_id.as_str())
                        .is_some_and(|child| child.kind == NodeKind::Claim)
            })
        {
            add_blocker(
                &mut blockers,
                &node.node_id,
                BlockerReason::StrategyWithoutSubclaim,
            );
        }

        if matches!(node.kind, NodeKind::TopClaim | NodeKind::Claim) {
            let claim = node.claim.as_ref().expect("node shape already validated");
            match claim.state {
                ClaimState::Supported => {}
                ClaimState::Contradicted => add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::ClaimContradicted,
                ),
                ClaimState::Unsupported => add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::ClaimUnsupported,
                ),
                ClaimState::Indeterminate => add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::ClaimIndeterminate,
                ),
            }
            let supporting_evidence: Vec<&AssuranceNode> = edges
                .iter()
                .filter(|edge| edge.to_node_id == node.node_id && edge.kind == EdgeKind::Supports)
                .filter_map(|edge| by_id.get(edge.from_node_id.as_str()).copied())
                .filter(|evidence| evidence.kind == NodeKind::Evidence)
                .collect();
            let requirement = policy
                .required_claim_evidence
                .iter()
                .find(|item| item.claim_id == node.node_id);
            let required_purposes = requirement
                .map(|item| item.required_purposes.as_slice())
                .unwrap_or(&[]);
            if requirement.is_none() {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::MissingClaimEvidenceRequirement,
                );
            }
            for purpose in required_purposes {
                let purpose_is_supported = supporting_evidence.iter().any(|evidence_node| {
                    evidence_node.evidence.as_ref().is_some_and(|evidence| {
                        evidence.purpose == *purpose
                            && evidence.disposition == EvidenceDisposition::Qualified
                    })
                });
                if !purpose_is_supported {
                    add_blocker(
                        &mut blockers,
                        &node.node_id,
                        BlockerReason::MissingRequiredEvidencePurpose,
                    );
                }
            }
            let eligible_evidence: Vec<&AssuranceNode> = supporting_evidence
                .iter()
                .copied()
                .filter(|evidence_node| {
                    evidence_node.evidence.as_ref().is_some_and(|evidence| {
                        required_purposes.contains(&evidence.purpose)
                            && evidence.disposition == EvidenceDisposition::Qualified
                    })
                })
                .collect();
            let independent_groups: BTreeSet<&str> = eligible_evidence
                .iter()
                .filter_map(|evidence| evidence.evidence.as_ref()?.correlation_group_id.as_deref())
                .collect();
            let group_count = independent_groups.len();
            groups_by_claim.push((node.node_id.clone(), group_count));
            let frozen_minimum = requirement
                .map(|item| item.minimum_independent_evidence_groups)
                .unwrap_or(usize::MAX);
            let minimum_groups = claim
                .minimum_independent_evidence_groups
                .max(frozen_minimum);
            if group_count < minimum_groups {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::InsufficientIndependentEvidenceGroups,
                );
            }
            let has_subclaim_strategy = edges
                .iter()
                .any(|edge| edge.from_node_id == node.node_id && edge.kind == EdgeKind::Decomposes);
            if supporting_evidence.is_empty() && !has_subclaim_strategy {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::ClaimWithoutSupportOrDecomposition,
                );
            }
        }
    }

    // Every evidence object remains distinct from its source authentication and physical truth.
    for node in nodes.iter().filter(|node| node.kind == NodeKind::Evidence) {
        let evidence = node
            .evidence
            .as_ref()
            .expect("node shape already validated");
        if evidence.effective_cutoff != policy.expected_scope.effective_cutoff
            || evidence.knowledge_cutoff != policy.expected_scope.knowledge_cutoff
        {
            return Err(EvaluationError::EvidenceCutoffMismatch);
        }
        match evidence.disposition {
            EvidenceDisposition::Qualified => {}
            EvidenceDisposition::HistoricalOnly | EvidenceDisposition::RequalificationRequired => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::EvidenceNotCurrent,
                );
            }
            EvidenceDisposition::Contradicted | EvidenceDisposition::Unsupported => {
                add_blocker(&mut blockers, &node.node_id, BlockerReason::EvidenceInvalid);
            }
            EvidenceDisposition::Indeterminate => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::EvidenceIndeterminate,
                );
            }
            EvidenceDisposition::PlanningOnly => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::NonOperationalEvidence,
                );
            }
        }
        if matches!(
            evidence.source_kind,
            EvidenceSourceKind::GenericSoftwareCi
                | EvidenceSourceKind::TrackVPlanning
                | EvidenceSourceKind::Other
        ) {
            add_blocker(
                &mut blockers,
                &node.node_id,
                BlockerReason::NonOperationalEvidence,
            );
        }
    }

    // Every required hazard must be explicitly represented and mitigated.
    for required in &policy.required_hazards {
        let hazard = nodes.iter().find(|node| {
            node.kind == NodeKind::Hazard && node.hazard_id.as_deref() == Some(required.as_str())
        });
        let Some(hazard) = hazard else {
            add_blocker(
                &mut blockers,
                required,
                BlockerReason::MissingRequiredHazard,
            );
            continue;
        };
        let has_argument_link = edges.iter().any(|edge| {
            edge.to_node_id == hazard.node_id
                && edge.kind == EdgeKind::AddressesHazard
                && by_id.get(edge.from_node_id.as_str()).is_some_and(|node| {
                    matches!(
                        node.kind,
                        NodeKind::TopClaim | NodeKind::Claim | NodeKind::Strategy
                    )
                })
        });
        if !has_argument_link {
            add_blocker(
                &mut blockers,
                required,
                BlockerReason::HazardNotLinkedToArgument,
            );
        }
        let mitigations: Vec<&AssuranceNode> = edges
            .iter()
            .filter(|edge| edge.to_node_id == hazard.node_id && edge.kind == EdgeKind::Mitigates)
            .filter_map(|edge| by_id.get(edge.from_node_id.as_str()).copied())
            .filter(|node| node.kind == NodeKind::Mitigation)
            .collect();
        if mitigations.is_empty() {
            add_blocker(
                &mut blockers,
                required,
                BlockerReason::HazardWithoutMitigation,
            );
        }
        for mitigation in mitigations {
            match mitigation.mitigation_state {
                Some(ClaimState::Supported) => {}
                Some(ClaimState::Indeterminate) => {
                    add_blocker(
                        &mut blockers,
                        &mitigation.node_id,
                        BlockerReason::MitigationIndeterminate,
                    );
                }
                Some(ClaimState::Contradicted | ClaimState::Unsupported) | None => {
                    add_blocker(
                        &mut blockers,
                        &mitigation.node_id,
                        BlockerReason::MitigationNotSupported,
                    );
                }
            }
            let has_evidence = edges.iter().any(|edge| {
                edge.to_node_id == mitigation.node_id
                    && edge.kind == EdgeKind::Supports
                    && by_id
                        .get(edge.from_node_id.as_str())
                        .is_some_and(|node| node.kind == NodeKind::Evidence)
            });
            if !has_evidence {
                add_blocker(
                    &mut blockers,
                    &mitigation.node_id,
                    BlockerReason::MitigationWithoutEvidence,
                );
            }
            let requirement = policy
                .required_mitigation_evidence
                .iter()
                .find(|item| item.mitigation_id == mitigation.node_id);
            let eligible_evidence: Vec<&AssuranceNode> = edges
                .iter()
                .filter(|edge| {
                    edge.to_node_id == mitigation.node_id && edge.kind == EdgeKind::Supports
                })
                .filter_map(|edge| by_id.get(edge.from_node_id.as_str()).copied())
                .filter(|evidence_node| {
                    evidence_node.evidence.as_ref().is_some_and(|evidence| {
                        evidence.disposition == EvidenceDisposition::Qualified
                            && requirement.is_some_and(|required| {
                                required.required_purposes.contains(&evidence.purpose)
                            })
                    })
                })
                .collect();
            let independent_groups: BTreeSet<&str> = eligible_evidence
                .iter()
                .filter_map(|evidence_node| {
                    evidence_node
                        .evidence
                        .as_ref()?
                        .correlation_group_id
                        .as_deref()
                })
                .collect();
            let required_groups = requirement
                .map(|item| item.minimum_independent_evidence_groups)
                .unwrap_or(usize::MAX);
            if independent_groups.len() < required_groups {
                add_blocker(
                    &mut blockers,
                    &mitigation.node_id,
                    BlockerReason::MitigationInsufficientIndependentEvidenceGroups,
                );
            }
        }
    }

    // Every supplied mitigation must attach to a required hazard and meet its frozen evidence predicates.
    for mitigation in nodes
        .iter()
        .filter(|node| node.kind == NodeKind::Mitigation)
    {
        if !edges.iter().any(|edge| {
            edge.from_node_id == mitigation.node_id
                && edge.kind == EdgeKind::Mitigates
                && by_id.get(edge.to_node_id.as_str()).is_some_and(|target| {
                    target.kind == NodeKind::Hazard
                        && target
                            .hazard_id
                            .as_ref()
                            .is_some_and(|id| policy.required_hazards.contains(id))
                })
        }) {
            add_blocker(
                &mut blockers,
                &mitigation.node_id,
                BlockerReason::MitigationNotAttachedToHazard,
            );
        }

        let requirement = policy
            .required_mitigation_evidence
            .iter()
            .find(|item| item.mitigation_id == mitigation.node_id);
        let Some(requirement) = requirement else {
            add_blocker(
                &mut blockers,
                &mitigation.node_id,
                BlockerReason::MissingMitigationEvidenceRequirement,
            );
            continue;
        };
        for purpose in &requirement.required_purposes {
            let purpose_is_supported = edges.iter().any(|edge| {
                edge.to_node_id == mitigation.node_id
                    && edge.kind == EdgeKind::Supports
                    && by_id
                        .get(edge.from_node_id.as_str())
                        .is_some_and(|evidence_node| {
                            evidence_node.kind == NodeKind::Evidence
                                && evidence_node.evidence.as_ref().is_some_and(|evidence| {
                                    evidence.purpose == *purpose
                                        && evidence.disposition == EvidenceDisposition::Qualified
                                })
                        })
            });
            if !purpose_is_supported {
                add_blocker(
                    &mut blockers,
                    &mitigation.node_id,
                    BlockerReason::MissingRequiredEvidencePurpose,
                );
            }
        }
    }

    // Assumptions must be supported or have an explicit authority decision.
    for node in nodes
        .iter()
        .filter(|node| node.kind == NodeKind::Assumption)
    {
        let assumption = node
            .assumption
            .as_ref()
            .expect("node shape already validated");
        match assumption.state {
            AssumptionState::Supported => {
                let has_evidence = edges.iter().any(|edge| {
                    edge.to_node_id == node.node_id
                        && edge.kind == EdgeKind::Supports
                        && by_id
                            .get(edge.from_node_id.as_str())
                            .is_some_and(|n| n.kind == NodeKind::Evidence)
                });
                if !has_evidence {
                    add_blocker(
                        &mut blockers,
                        &node.node_id,
                        BlockerReason::AssumptionWithoutSupport,
                    );
                }
            }
            AssumptionState::AcceptedByAuthority => {
                if !has_accepted_decision_edge(node, edges, &by_id, policy) {
                    add_blocker(
                        &mut blockers,
                        &node.node_id,
                        BlockerReason::AssumptionWithoutSupport,
                    );
                }
            }
            AssumptionState::Open => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::UnresolvedAssumption,
                );
            }
            AssumptionState::Unknown => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::AssumptionUnknown,
                );
            }
            AssumptionState::Expired => {
                add_blocker(
                    &mut blockers,
                    &node.node_id,
                    BlockerReason::EvidenceNotCurrent,
                );
            }
        }
    }

    // Every defeater must challenge a claim or mitigation and then be resolved/accepted.
    for node in nodes.iter().filter(|node| node.kind == NodeKind::Defeater) {
        if !edges.iter().any(|edge| {
            edge.from_node_id == node.node_id
                && edge.kind == EdgeKind::Challenges
                && by_id.get(edge.to_node_id.as_str()).is_some_and(|target| {
                    matches!(
                        target.kind,
                        NodeKind::TopClaim | NodeKind::Claim | NodeKind::Mitigation
                    )
                })
        }) {
            add_blocker(
                &mut blockers,
                &node.node_id,
                BlockerReason::DefeaterWithoutChallenge,
            );
        }
        let defeater = node
            .defeater
            .as_ref()
            .expect("node shape already validated");
        match defeater.state {
            DefeaterState::Open | DefeaterState::Unknown => {
                add_blocker(&mut blockers, &node.node_id, BlockerReason::OpenDefeater);
            }
            DefeaterState::ResolvedWithEvidence => {
                let has_discharge = edges.iter().any(|edge| {
                    edge.to_node_id == node.node_id
                        && edge.kind == EdgeKind::Discharges
                        && by_id.get(edge.from_node_id.as_str()).is_some_and(|n| {
                            n.kind == NodeKind::Evidence
                                && n.evidence.as_ref().is_some_and(|e| {
                                    e.disposition == EvidenceDisposition::Qualified
                                })
                        })
                });
                if !has_discharge {
                    add_blocker(
                        &mut blockers,
                        &node.node_id,
                        BlockerReason::DefeaterWithoutDischarge,
                    );
                }
            }
            DefeaterState::AcceptedByAuthority | DefeaterState::NotApplicableApproved => {
                if !has_accepted_decision_edge(node, edges, &by_id) {
                    add_blocker(
                        &mut blockers,
                        &node.node_id,
                        BlockerReason::DefeaterWithoutAuthorityDecision,
                    );
                }
            }
        }
    }

    let mut outstanding_authority_roles = Vec::new();
    for required in &policy.required_authorities {
        let decisions: Vec<&AssuranceNode> = nodes
            .iter()
            .filter(|node| node.kind == NodeKind::AuthorityDecision)
            .filter(|node| {
                node.authority_decision.as_ref().is_some_and(|decision| {
                    decision.role == required.role && decision.authority_id == required.authority_id
                })
            })
            .collect();
        if decisions.is_empty() {
            add_blocker(
                &mut blockers,
                &required.role,
                BlockerReason::MissingAuthorityDecision,
            );
            outstanding_authority_roles.push(required.role.clone());
            continue;
        }
        if decisions.len() > 1 {
            return Err(EvaluationError::DuplicateAuthorityDecision);
        }
        let decision = decisions[0]
            .authority_decision
            .as_ref()
            .expect("node shape already validated");
        match decision.status {
            AuthorityDecisionStatus::Accepted
                if decision.effective_at <= policy.expected_scope.operation_start
                    && decision.recorded_at <= policy.expected_scope.knowledge_cutoff
                    && decision
                        .valid_until
                        .is_none_or(|end| end >= policy.expected_scope.operation_end) => {}
            AuthorityDecisionStatus::Pending => {
                outstanding_authority_roles.push(required.role.clone());
                add_blocker(
                    &mut blockers,
                    &required.role,
                    BlockerReason::AuthorityDecisionOutstanding,
                );
            }
            AuthorityDecisionStatus::Accepted => {
                outstanding_authority_roles.push(required.role.clone());
                add_blocker(
                    &mut blockers,
                    &required.role,
                    BlockerReason::AuthorityDecisionOutstanding,
                );
            }
            AuthorityDecisionStatus::Rejected
            | AuthorityDecisionStatus::Revoked
            | AuthorityDecisionStatus::Expired => {
                outstanding_authority_roles.push(required.role.clone());
                add_blocker(
                    &mut blockers,
                    &required.role,
                    BlockerReason::AuthorityDecisionRejectedOrExpired,
                );
            }
        }
    }

    // Every supplied decision node must be attached to an explicit dependent argument node.
    for decision_node in nodes
        .iter()
        .filter(|node| node.kind == NodeKind::AuthorityDecision)
    {
        if !edges.iter().any(|edge| {
            edge.to_node_id == decision_node.node_id && edge.kind == EdgeKind::RequiresDecision
        }) {
            add_blocker(
                &mut blockers,
                &decision_node.node_id,
                BlockerReason::AuthorityDecisionMismatch,
            );
        }
    }

    let status = select_status(&blockers);
    let blockers: Vec<CaseBlocker> = blockers
        .into_iter()
        .map(|(subject_id, reason)| CaseBlocker { subject_id, reason })
        .collect();
    outstanding_authority_roles.sort_unstable();
    groups_by_claim.sort_by(|left, right| left.0.cmp(&right.0));

    Ok(AssuranceResult {
        status,
        case_id: policy.expected_scope.case_id.clone(),
        root_claim_id: root_claim_id.to_owned(),
        policy_sha256: policy.policy_sha256.clone(),
        verifier_build_sha256: policy.verifier_build_sha256.clone(),
        blockers,
        outstanding_authority_roles,
        independent_evidence_groups_by_claim: groups_by_claim,
        permission_granted: false,
    })
}

fn has_accepted_decision_edge(
    node: &AssuranceNode,
    edges: &[AssuranceEdge],
    by_id: &BTreeMap<&str, &AssuranceNode>,
    policy: &AssuranceCasePolicy,
) -> bool {
    edges.iter().any(|edge| {
        edge.from_node_id == node.node_id
            && edge.kind == EdgeKind::RequiresDecision
            && by_id
                .get(edge.to_node_id.as_str())
                .is_some_and(|decision_node| {
                    decision_node
                        .authority_decision
                        .as_ref()
                        .is_some_and(|decision| {
                            decision.status == AuthorityDecisionStatus::Accepted
                                && decision.effective_at <= policy.expected_scope.operation_start
                                && decision.recorded_at <= policy.expected_scope.knowledge_cutoff
                                && decision
                                    .valid_until
                                    .is_none_or(|end| end >= policy.expected_scope.operation_end)
                                && policy.required_authorities.iter().any(|required| {
                                    required.role == decision.role
                                        && required.authority_id == decision.authority_id
                                })
                        })
                })
    })
}

fn select_status(blockers: &BTreeSet<(String, BlockerReason)>) -> AssuranceStatus {
    if blockers.is_empty() {
        return AssuranceStatus::ReviewReadyOnly;
    }
    if blockers
        .iter()
        .any(|(_, reason)| *reason == BlockerReason::OpenDefeater)
    {
        return AssuranceStatus::BlockedByOpenDefeater;
    }
    if blockers.iter().any(|(_, reason)| {
        matches!(
            reason,
            BlockerReason::EvidenceNotCurrent
                | BlockerReason::EvidenceInvalid
                | BlockerReason::NonOperationalEvidence
                | BlockerReason::ClaimContradicted
                | BlockerReason::ClaimUnsupported
                | BlockerReason::MitigationNotSupported
                | BlockerReason::AuthorityDecisionRejectedOrExpired
        )
    }) {
        return AssuranceStatus::BlockedByUnsupportedOrStaleEvidence;
    }
    if blockers.iter().any(|(_, reason)| {
        *reason == BlockerReason::EvidenceIndeterminate
            || *reason == BlockerReason::ClaimIndeterminate
            || *reason == BlockerReason::InsufficientIndependentEvidenceGroups
            || *reason == BlockerReason::MitigationIndeterminate
            || *reason == BlockerReason::AssumptionUnknown
    }) {
        return AssuranceStatus::Indeterminate;
    }
    AssuranceStatus::IncompleteArgument
}
