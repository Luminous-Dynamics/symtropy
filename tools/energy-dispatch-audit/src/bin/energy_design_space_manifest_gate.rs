//! Fail-closed checks for Symthaea's bounded parametric design-space manifest.

use std::{collections::BTreeMap, env, error::Error, fs, io, path::Path};

fn expected_id(pv: u32, capacity: u32, battery_power: u32, grid_power: u32) -> String {
    format!(
        "synthetic-parametric-pv-{pv}kw-battery-{capacity}kwh-battery-power-{battery_power}kw-grid-{grid_power}kw"
    )
}

fn run() -> Result<(), Box<dyn Error>> {
    let args = env::args().collect::<Vec<_>>();
    if args.len() != 3 {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "usage: energy_design_space_manifest_gate <design-space-manifest.json> <candidate-output-directory>",
        )
        .into());
    }

    let bytes = fs::read(&args[1])?;
    let manifest: serde_json::Value = serde_json::from_slice(&bytes)?;
    let candidate_count = manifest
        .get("candidates")
        .and_then(serde_json::Value::as_array)
        .map(Vec::len)
        .ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                "manifest candidates must be an array",
            )
        })?;
    let rejected_count = manifest
        .get("rejected_candidates")
        .and_then(serde_json::Value::as_array)
        .map(Vec::len)
        .ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                "manifest rejected_candidates must be an array",
            )
        })?;

    let requested = manifest
        .get("requested_candidate_count")
        .and_then(serde_json::Value::as_u64);
    let search_schema = manifest
        .get("search_schema_version")
        .and_then(serde_json::Value::as_str);
    let claim_ceiling = manifest
        .get("claim_ceiling")
        .and_then(serde_json::Value::as_str);

    let axes = manifest.get("axis_values").and_then(serde_json::Value::as_object);
    let axes_match = axes.is_some_and(|axes| {
        let expected = [
            ("pv_rated_power_kw", vec![1.0, 2.0, 3.0]),
            ("battery_capacity_kwh", vec![1.0, 2.0, 3.0]),
            ("battery_charge_discharge_power_kw", vec![1.0, 2.0]),
            ("grid_import_power_kw", vec![1.0, 2.0]),
        ];
        expected.iter().all(|(key, values)| {
            axes.get(*key)
                .and_then(serde_json::Value::as_array)
                .is_some_and(|actual| {
                    actual.len() == values.len()
                        && actual.iter().zip(values.iter()).all(|(actual, expected)| {
                            actual.as_f64().is_some_and(|actual| (actual - *expected).abs() < f64::EPSILON)
                        })
                })
        }) && axes.len() == expected.len()
    });

    let mut expected_ids = Vec::with_capacity(36);
    for pv in [1, 2, 3] {
        for capacity in [1, 2, 3] {
            for battery_power in [1, 2] {
                for grid_power in [1, 2] {
                    expected_ids.push(expected_id(pv, capacity, battery_power, grid_power));
                }
            }
        }
    }
    let candidates = manifest["candidates"].as_array().expect("array checked above");
    let mut manifest_by_id = BTreeMap::new();
    let mut actual_ids = Vec::with_capacity(candidates.len());
    for candidate in candidates {
        let Some(id) = candidate.get("candidate_id").and_then(serde_json::Value::as_str) else {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "candidate in design-space manifest has no string candidate_id",
            ).into());
        };
        actual_ids.push(id.to_owned());
        manifest_by_id.insert(id.to_owned(), candidate);
    }
    actual_ids.sort();
    expected_ids.sort();
    let unique_ids = actual_ids.windows(2).all(|pair| pair[0] != pair[1]);
    let ids_match = actual_ids == expected_ids;
    let all_synthetic = candidates.iter().all(|candidate| {
        candidate.get("synthetic").and_then(serde_json::Value::as_bool) == Some(true)
    });

    // Bind each exported candidate file to the corresponding object in the
    // frozen manifest. Both are generated by the same exact Symthaea CLI head.
    let candidate_dir = Path::new(&args[2]);
    let mut candidate_files_match = true;
    for id in &expected_ids {
        let Some(manifest_candidate) = manifest_by_id.get(id) else {
            candidate_files_match = false;
            continue;
        };
        let path = candidate_dir.join(id).join("candidate.json");
        let file_bytes = fs::read(path)?;
        let file_candidate: serde_json::Value = serde_json::from_slice(&file_bytes)?;
        if &file_candidate != *manifest_candidate {
            candidate_files_match = false;
        }
    }
    let synthetic_ceiling = claim_ceiling.is_some_and(|claim| {
        claim.contains("synthetic sizing sweep")
            && claim.contains("no real-site optimization")
            && claim.contains("physical-safety")
            && claim.contains("field-performance")
    });

    let accepted = search_schema == Some("energy-architecture-search-v0.1")
        && requested == Some(36)
        && candidate_count == 36
        && rejected_count == 0
        && axes_match
        && unique_ids
        && ids_match
        && candidate_files_match
        && all_synthetic
        && synthetic_ceiling;

    println!(
        "search_schema={:?} requested={:?} emitted={} rejected={} axes_match={} unique_ids={} IDs_match={} exported_files_match={} all_synthetic={} claim_ceiling_ok={}",
        search_schema,
        requested,
        candidate_count,
        rejected_count,
        axes_match,
        unique_ids,
        ids_match,
        candidate_files_match,
        all_synthetic,
        synthetic_ceiling
    );
    if !accepted {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "bounded design-space manifest failed its frozen 36-candidate contract",
        ).into());
    }

    println!("PASS: all 36 expected parameter combinations are present and uniquely identified; no candidates were silently dropped.");
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("design-space manifest gate failed: {error}");
        std::process::exit(2);
    }
}
